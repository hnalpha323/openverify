Opener = Callable[[str, float], Any]
"""``opener(url, timeout_seconds)`` returns a readable context-manager response."""

Runner = Callable[..., Any]
"""``runner(command, **subprocess_run_kwargs)``, ``subprocess.run`` by default."""


def _default_opener(url: str, timeout: float) -> Any:
    request = urllib.request.Request(
        url, headers={"User-Agent": "openverify-fetch-k8s-schemas"}
    )
    return urllib.request.urlopen(request, timeout=timeout)


def _sha256_of(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(CHUNK_SIZE), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _matches(path: Path, pin: Pin) -> bool:
    return (
        path.is_file()
        and path.stat().st_size == pin.size
        and _sha256_of(path) == pin.sha256
    )


def _download_once(pin: Pin, cache_dir: Path, opener: Opener) -> Path:
    target = cache_dir / pin.filename
    handle, name = tempfile.mkstemp(prefix=f".{pin.filename}.", dir=cache_dir)
    temporary = Path(name)
    try:
        digest = hashlib.sha256()
        received = 0
        with (
            os.fdopen(handle, "wb") as out,
            opener(pin.url, DEFAULT_TIMEOUT_SECONDS) as response,
        ):
            while chunk := response.read(CHUNK_SIZE):
                received += len(chunk)
                if received > pin.size:
                    raise DownloadTooLargeError(
                        f"{pin.filename}: more than the pinned {pin.size} bytes from {pin.url}"
                    )
                digest.update(chunk)
                out.write(chunk)
        if received != pin.size:
            raise FetchError(
                f"{pin.filename}: {received} bytes from {pin.url}, the pin says {pin.size}"
            )
        if digest.hexdigest() != pin.sha256:
            raise ChecksumMismatchError(
                f"{pin.filename}: sha256 {digest.hexdigest()} from {pin.url}, "
                f"the pin says {pin.sha256}"
            )
        temporary.replace(target)
        return target
    finally:
        temporary.unlink(missing_ok=True)


def fetch(
    pin: Pin,
    cache_dir: Path,
    *,
    opener: Opener | None = None,
    sleep: Callable[[float], None] | None = None,
) -> Path:
    """Return ``cache_dir/<filename>`` holding the pinned bytes, downloading them if needed.

    The file is written only after its size and SHA-256 match. A transient network failure is
    retried (three attempts in all); a size or digest mismatch never is.
    """
    if not pin.url.startswith("https://"):
        raise FetchError(
            f"{pin.filename}: refusing {pin.url}, only https downloads are allowed"
        )
    cache_dir.mkdir(parents=True, exist_ok=True)
    cached = cache_dir / pin.filename
    if _matches(cached, pin):
        return cached
    open_url = opener if opener is not None else _default_opener
    wait = sleep if sleep is not None else time.sleep
    last: Exception | None = None
    for attempt in range(1, ATTEMPTS + 1):
        try:
            return _download_once(pin, cache_dir, open_url)
        except FetchError:
            raise
        except (urllib.error.URLError, TimeoutError, ConnectionError) as error:
            last = error
            if attempt < ATTEMPTS:
                wait(RETRY_SECONDS * attempt)
    raise FetchError(
        f"{pin.filename}: {pin.url} failed after {ATTEMPTS} attempts: {last}"
    )


def default_python() -> list[str]:
    """The interpreter that runs the converter: the supply-chain environment, which has PyYAML."""
    venv = SUPPLY_CHAIN_PROJECT / ".venv" / "bin" / "python"
    if venv.exists():
        return [str(venv), "-I"]
    return [
        "uv",
        "run",
        "--project",
        str(SUPPLY_CHAIN_PROJECT),
        "--frozen",
        "python",
        "-I",
    ]


def _reference(node: Mapping[str, Any]) -> str | None:
    """The definition a node refers to, or None (a property named ``$ref`` holds a schema)."""
    ref = node.get("$ref")
    if not isinstance(ref, str):
        return None
    if not ref.startswith(DEFINITIONS_PREFIX):
        raise FetchError(
            f"unsupported reference {ref}: only {DEFINITIONS_PREFIX}<name> is read"
        )
    return ref[len(DEFINITIONS_PREFIX) :]


def _expand(definitions: Mapping[str, Any], node: Any, stack: frozenset[str]) -> Any:
    if isinstance(node, list):
        return [_expand(definitions, item, stack) for item in node]
    if not isinstance(node, dict):
        return node
    name = _reference(node)
    if name is None:
        return {key: _expand(definitions, value, stack) for key, value in node.items()}
    if name not in definitions:
        raise FetchError(f"reference to a missing definition: {name}")
    expanded: dict[str, Any] = (
        {}
        if name in stack
        else dict(_expand(definitions, definitions[name], stack | {name}))
    )
    for key, value in node.items():
        if key != "$ref":
            expanded[key] = _expand(definitions, value, stack)
    return expanded


def expand_definition(definitions: Mapping[str, Any], name: str) -> dict[str, Any]:
    """The definition ``name`` with every reference inlined (a recursive one becomes ``{}``)."""
    if name not in definitions:
        raise FetchError(f"no definition named {name}")
    expanded = _expand(definitions, definitions[name], frozenset({name}))
    if not isinstance(expanded, dict):
        raise FetchError(f"definition {name} is not an object")
    return expanded


def _file_name(group: str, version: str, kind: str) -> str:
    """The name the converter writes, which is the file kubeconform looks for."""
    template = CORE_FORMAT if group == "" else GROUPED_FORMAT
    return template.format(
        kind=kind, group=group.split(".")[0], version=version
    ).lower()


def crd_batches(
    swagger: Mapping[str, Any],
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """One CustomResourceDefinition per group, version and kind: the core ones, then the grouped."""
    definitions = swagger.get("definitions")
    if swagger.get("swagger") != "2.0" or not isinstance(definitions, dict):
        raise FetchError(
            "the document is not a Kubernetes Swagger 2.0 document with definitions"
        )
    seen: dict[str, str] = {}
    entries: list[tuple[tuple[str, str, str], dict[str, Any]]] = []
    for name in sorted(definitions):
        definition = definitions[name]
        kinds = definition.get(GVK_KEY) if isinstance(definition, dict) else None
        if not kinds:
            continue
        schema = expand_definition(definitions, name)
        for gvk in kinds:
            group, version, kind = (
                str(gvk["group"]),
                str(gvk["version"]),
                str(gvk["kind"]),
            )
            file_name = _file_name(group, version, kind)
            if file_name in seen:
                raise FetchError(
                    f"{name} and {seen[file_name]} would both write {file_name}.json"
                )
            seen[file_name] = name
            crd = {
                "apiVersion": "apiextensions.k8s.io/v1",
                "kind": "CustomResourceDefinition",
                "spec": {
                    "group": group,
                    "names": {"kind": kind},
                    "versions": [
                        {"name": version, "schema": {"openAPIV3Schema": schema}}
                    ],
                },
            }
            entries.append(((group, version, kind), crd))
    entries.sort(key=lambda entry: entry[0])
    core = [crd for (group, _version, _kind), crd in entries if group == ""]
    grouped = [crd for (group, _version, _kind), crd in entries if group != ""]
    return core, grouped


def bundle_digest(directory: Path) -> tuple[str, str]:
    """``SHA256SUMS`` text over the directory's schemas (sorted by name) and its own SHA-256."""
    lines = [
        f"{_sha256_of(path)}  {path.name}\n"
        for path in sorted(directory.glob("*.json"), key=lambda p: p.name)
    ]
    sums = "".join(lines)
    return sums, hashlib.sha256(sums.encode()).hexdigest()


def _complete(directory: Path, expected: str) -> bool:
    sums_file = directory / SUMS_FILE
    if not sums_file.is_file():
        return False
    sums, digest = bundle_digest(directory)
    return digest == expected and sums_file.read_text() == sums


def _convert(
    runner: Runner,
    python: Sequence[str],
    converter: Path,
    batch: list[dict[str, Any]],
    work: Path,
    out: Path,
    filename_format: str,
) -> None:
    if not batch:
        return
    batch_file = work / (
        "core.json" if filename_format == CORE_FORMAT else "grouped.json"
    )
    batch_file.write_text(json.dumps({"items": batch}))
    env = {
        **os.environ,
        "FILENAME_FORMAT": filename_format,
        "DENY_ROOT_ADDITIONAL_PROPERTIES": "1",
    }
    try:
        runner(
            [*python, str(converter), str(batch_file)],
            cwd=out,
            env=env,
            check=True,
            stdout=subprocess.DEVNULL,
        )
    except (subprocess.CalledProcessError, OSError) as error:
        raise FetchError(
            f"the pinned converter failed ({filename_format}): {error}"
        ) from error


def generate(
    release: KubernetesRelease,
    dest: Path,
    cache_dir: Path,
    python: Sequence[str],
    *,
    opener: Opener | None = None,
    runner: Runner | None = None,
    converter: Pin | None = None,
) -> tuple[str, str]:
    """Build ``dest/v<version>/`` and return ``("present" | "generated", bundle sha256)``.

    ``converter`` defaults to the module's ``CONVERTER`` pin, read at call time.
    """
    target = dest / f"v{release.version}"
    if _complete(target, release.bundle_sha256):
        return "present", release.bundle_sha256
    document_path = fetch(release.document, cache_dir, opener=opener)
    converter_path = fetch(converter or CONVERTER, cache_dir, opener=opener)
    swagger = json.loads(document_path.read_text())
    core, grouped = crd_batches(swagger)
    dest.mkdir(parents=True, exist_ok=True)
    run = runner if runner is not None else subprocess.run
    with tempfile.TemporaryDirectory(
        prefix=f".v{release.version}.", dir=dest
    ) as scratch:
        work = Path(scratch) / "work"
        out = Path(scratch) / "out"
        work.mkdir()
        out.mkdir()
        _convert(run, python, converter_path, core, work, out, CORE_FORMAT)
        _convert(run, python, converter_path, grouped, work, out, GROUPED_FORMAT)
        sums, digest = bundle_digest(out)
        if digest != release.bundle_sha256:
            raise BundleMismatchError(
                f"v{release.version}: the bundle sha256 {digest} does not match its pin "
                f"{release.bundle_sha256}"
            )
        (out / SUMS_FILE).write_text(sums)
        if target.exists():
            shutil.rmtree(target)
        out.replace(target)
    return "generated", digest


def schema_location(release: KubernetesRelease, dest: Path) -> str:
    """The ``-schema-location`` template kubeconform reads this version's bundle with."""
    return (
        f"{dest}/v{release.version}/{{{{ .ResourceKind }}}}{{{{ .KindSuffix }}}}.json"
    )


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Generate the offline Kubernetes schemas kubeconform reads (C265.3)."
    )
    parser.add_argument(
        "--version",
        action="append",
        dest="versions",
        metavar="MINOR",
        help="a pinned minor version (1.35, 1.36 or 1.37); repeatable; default every one",
    )
    parser.add_argument(
        "--dest", type=Path, default=DEFAULT_DEST, help="the bundle directory"
    )
    parser.add_argument(
        "--cache",
        type=Path,
        help="where the pinned downloads are kept (default <dest>/.downloads)",
    )
    parser.add_argument(
        "--python",
        help="an interpreter with PyYAML for the converter (default security/python)",
    )
    parser.add_argument(
        "--print-location",
        metavar="MINOR",
        help="print the kubeconform -schema-location of a pinned minor version and exit",
    )
    return parser


def _release_for(parser: argparse.ArgumentParser, minor: str) -> KubernetesRelease:
    release = KUBERNETES_RELEASES.get(minor)
    if release is None:
        parser.error(f"{minor} is not pinned; pinned: {', '.join(KUBERNETES_RELEASES)}")
    return release


def main(argv: Sequence[str] | None = None) -> int:
    parser = _parser()
    args = parser.parse_args(argv)
    dest: Path = args.dest
    if args.print_location is not None:
        print(schema_location(_release_for(parser, args.print_location), dest))
        return 0
    releases = [
        _release_for(parser, minor) for minor in (args.versions or KUBERNETES_RELEASES)
    ]
    cache: Path = args.cache if args.cache is not None else dest / ".downloads"
    python = [args.python, "-I"] if args.python else default_python()
    try:
        for release in releases:
            status, digest = generate(release, dest, cache, python)
            count = len(list((dest / f"v{release.version}").glob("*.json")))
            print(
                f"v{release.version}: {status}, {count} schemas, bundle sha256 {digest}"
            )
    except FetchError as error:
        print(f"fetch_k8s_schemas: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
