from typing import Any, Final

REPO_ROOT: Final = Path(__file__).resolve().parent.parent
DEFAULT_DEST: Final = REPO_ROOT / "data" / "k8s-schemas"
SUPPLY_CHAIN_PROJECT: Final = REPO_ROOT / "security" / "python"
DEFAULT_TIMEOUT_SECONDS: Final = 60.0
CHUNK_SIZE: Final = 1 << 16
ATTEMPTS: Final = 3
RETRY_SECONDS: Final = 2.0
DEFINITIONS_PREFIX: Final = "#/definitions/"
SUMS_FILE: Final = "SHA256SUMS"
CORE_FORMAT: Final = "{kind}-{version}"
GROUPED_FORMAT: Final = "{kind}-{group}-{version}"
GVK_KEY: Final = "x-kubernetes-group-version-kind"


class FetchError(Exception):
    """A pinned file could not be fetched or a bundle could not be built."""


class ChecksumMismatchError(FetchError):
    """The downloaded bytes do not match the pinned SHA-256."""


class DownloadTooLargeError(FetchError):
    """The server sent more bytes than the pin declares."""


class BundleMismatchError(FetchError):
    """The generated schema bundle does not match its pinned SHA-256."""


@dataclass(frozen=True, slots=True)
class Pin:
    """One pinned download."""

    filename: str
    url: str
    sha256: str
    size: int


@dataclass(frozen=True, slots=True)
class KubernetesRelease:
    """One Kubernetes minor version's pinned OpenAPI document and the bundle it yields."""

    minor: str
    version: str
    commit: str
    document: Pin
    bundle_sha256: str


def _release(
    minor: str, version: str, commit: str, size: int, sha256: str, bundle_sha256: str
) -> KubernetesRelease:
    url = (
        f"https://raw.githubusercontent.com/kubernetes/kubernetes/v{version}"
        "/api/openapi-spec/swagger.json"
    )
    document = Pin(
        filename=f"swagger-v{version}.json", url=url, sha256=sha256, size=size
    )
    return KubernetesRelease(minor, version, commit, document, bundle_sha256)


