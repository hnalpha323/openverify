const codeList = (groups: Readonly<Record<string, readonly string[]>>): string[] =>
  Object.entries(groups).flatMap(([title, lines]) => [
    `- **${title}:** ${lines
      .flatMap((line) => line.split(' '))
      .map((code) => `\`${code}\``)
      .join(', ')}.`,
  ]);

