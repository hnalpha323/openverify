"""C214.5: the consumer check's verification metadata, over a synthetic file in Gradle's format."""

from __future__ import annotations

import unittest

from support import load

tool = load("trust-staged-group")

GENERATED = """<?xml version="1.0" encoding="UTF-8"?>
<verification-metadata xmlns="https://schema.gradle.org/dependency-verification">
   <configuration>
      <verify-metadata>true</verify-metadata>
      <verify-signatures>false</verify-signatures>
   </configuration>
   <components>
      <component group="androidx.activity" name="activity" version="1.13.0">
         <artifact name="activity-1.13.0.aar">
            <sha256 value="aa" origin="Generated by Gradle"/>
         </artifact>
      </component>
      <component group="dev.example" name="openverify-sdk" version="0.1.0">
         <artifact name="openverify-sdk-0.1.0.module">
            <sha256 value="bb" origin="Generated by Gradle"/>
         </artifact>
      </component>
      <component group="dev.example" name="openverify-sdk-android" version="0.1.0">
         <artifact name="openverify-sdk.aar">
            <sha256 value="cc" origin="Generated by Gradle"/>
         </artifact>
      </component>
      <component group="dev.examples" name="other" version="1">
         <artifact name="other-1.jar">
            <sha256 value="dd" origin="Generated by Gradle"/>
         </artifact>
      </component>
   </components>
</verification-metadata>
"""


class TrustStagedGroup(unittest.TestCase):
    def test_the_groups_checksums_go_and_one_trust_entry_comes(self) -> None:
        text = tool.trust_group(GENERATED, "dev.example")
        self.assertNotIn('group="dev.example"', text.replace('<trust group="dev.example"/>', ""))
        self.assertEqual(1, text.count('<trust group="dev.example"/>'))
        self.assertIn("<trusted-artifacts>", text.split("</configuration>")[0])

    def test_every_other_component_stays_as_gradle_wrote_it(self) -> None:
        text = tool.trust_group(GENERATED, "dev.example")
        for kept in ('group="androidx.activity"', 'value="aa"', 'group="dev.examples" name="other"', 'value="dd"'):
            self.assertIn(kept, text)
        for gone in ('value="bb"', 'value="cc"'):
            self.assertNotIn(gone, text)

    def test_it_is_idempotent(self) -> None:
        once = tool.trust_group(GENERATED, "dev.example")
        self.assertEqual(once, tool.trust_group(once, "dev.example"))

    def test_a_file_without_a_configuration_block_is_refused(self) -> None:
        with self.assertRaises(ValueError):
            tool.trust_group("<verification-metadata/>", "dev.example")

    def test_the_committed_file_trusts_only_the_staged_group_and_holds_none_of_its_checksums(self) -> None:
        text = tool.METADATA_PATH.read_text(encoding="utf-8")
        group = tool.staged_group()
        self.assertEqual([f'<trust group="{group}"/>'], [line.strip() for line in text.splitlines() if "<trust " in line])
        self.assertNotIn(f'<component group="{group}"', text)
        self.assertIn("<verify-metadata>true</verify-metadata>", text)
        self.assertGreater(text.count("<component "), 100)


if __name__ == "__main__":
    unittest.main()
