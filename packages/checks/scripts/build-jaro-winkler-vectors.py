#!/usr/bin/env python3
# /// script
# requires-python = ">=3.12"
# dependencies = ["jellyfish==1.2.1", "rapidfuzz==3.14.6"]
# ///
"""Write packages/checks/data/jaro-winkler-vectors.json (plan C58.7): Jaro and Jaro-Winkler
reference values for our own implementation (src/name-matching.ts), computed offline by two
independent MIT-licensed oracles, jellyfish 1.2.1 and rapidfuzz 3.14.6, with the defaults ours
uses (prefix scale 0.1 over at most four characters, the boost only above a Jaro of 0.7, no
long-string adjustment). A pair is written only when both oracles agree to 1e-12; the build stops
otherwise. Dev only: never run in CI, and nothing here ships.

    uv run --script packages/checks/scripts/build-jaro-winkler-vectors.py

The pairs are our own: synthetic names, street and city words, near-threshold cases for the
0.90 and 0.92 thresholds the matchers use, and Unicode cases (code points, astral characters).
Two empty strings are left out: ours scores them 1, as name-matching.test.ts pins.
"""

from __future__ import annotations

import json
import sys
from importlib.metadata import version
from pathlib import Path

import jellyfish
from rapidfuzz.distance import Jaro, JaroWinkler

OUTPUT = Path(__file__).resolve().parent.parent / "data" / "jaro-winkler-vectors.json"
TOLERANCE = 1e-12

PAIRS: list[tuple[str, str]] = [
    # The classic Winkler pairs.
    ("martha", "marhta"),
    ("dwayne", "duane"),
    ("dixon", "dicksonx"),
    ("crate", "trace"),
    ("jones", "johnson"),
    # Synthetic family names with one slip.
    ("vellacott", "velacott"),
    ("vellacott", "vellacot"),
    ("vellacott", "vallacott"),
    ("ostrander", "ostrandr"),
    ("ostrander", "oostrander"),
    ("harrowgate", "harrogate"),
    ("quillon", "quilon"),
    ("quillon", "qillon"),
    # Given names: spelling variants that are not nicknames.
    ("stephen", "steven"),
    ("catherine", "katherine"),
    ("catherine", "kathryn"),
    ("katharina", "katherina"),
    ("mohammed", "muhammad"),
    ("nguyen", "ngyuen"),
    ("smith", "smyth"),
    ("jon", "john"),
    ("ann", "anne"),
    ("ada", "adam"),
    ("bob", "bobby"),
    ("william", "willaim"),
    ("jonah", "john"),
    ("j", "john"),
    # Folded renderings.
    ("muller", "mueller"),
    ("strasse", "strase"),
    ("rosenstrasse", "rosenstrase"),
    # Street, city and business words near the 0.92 and 0.90 thresholds.
    ("quillon street", "quillon st"),
    ("quillon widget", "quillon widgets"),
    ("quillon widgets", "quillon widgets international"),
    ("lanternfield", "lanternfeld"),
    ("lanternfield", "lanternfields"),
    ("lanternfield", "lantern field"),
    ("quillonville", "quillonvile"),
    ("quillonbridge", "quillonbrige"),
    ("tilleuls", "tilleul"),
    # Short strings and transpositions.
    ("a", "a"),
    ("a", "b"),
    ("ab", "ba"),
    ("abc", "abd"),
    ("abcdefgh", "abcdefhg"),
    ("o", "oo"),
    ("", "anna"),
    # Unicode: code points, not UTF-16 units.
    ("josé", "jose"),
    ("zoë", "zoe"),
    ("straße", "strasse"),
    ("иван", "иванн"),
    ("иван", "ivan"),
    ("李小龍", "李小龙"),
    ("\U0001d49cnna", "anna"),
    ("\U0001d49cnna", "\U0001d49cnne"),
]


def main() -> int:
    vectors = []
    for a, b in PAIRS:
        jaro = jellyfish.jaro_similarity(a, b)
        winkler = jellyfish.jaro_winkler_similarity(a, b)
        jaro_rf = Jaro.similarity(a, b)
        winkler_rf = JaroWinkler.similarity(a, b, prefix_weight=0.1)
        if abs(jaro - jaro_rf) > TOLERANCE or abs(winkler - winkler_rf) > TOLERANCE:
            print(f"oracles disagree on {a!r} / {b!r}: {jaro}/{jaro_rf}, {winkler}/{winkler_rf}")
            return 1
        vectors.append({"a": a, "b": b, "jaro": jaro, "jaro-winkler": winkler})
    document = {
        "description": (
            "Jaro and Jaro-Winkler reference values for packages/checks/src/name-matching.ts "
            "(plan C58.7), computed offline by jellyfish and rapidfuzz, which agree on every pair "
            "to 1e-12. Prefix scale 0.1 over at most four characters, boost above a Jaro of 0.7, "
            "no long-string adjustment. Generated by "
            "packages/checks/scripts/build-jaro-winkler-vectors.py; the pairs are our own."
        ),
        "oracles": {
            "jellyfish": version("jellyfish"),
            "rapidfuzz": version("rapidfuzz"),
        },
        "licence": "The oracles are MIT-licensed dev tools, not shipped; the values are facts.",
        "vectors": vectors,
    }
    OUTPUT.write_text(json.dumps(document, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {len(vectors)} vectors to {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
