const HEADER = (title: string): string =>
  `# ${title}\n\n<!-- Generated by \`pnpm --filter @openverify/api workflow-docs:write\`: edit the code, not this file. -->\n`;

const scopesOf = (entry: AnyActionRegistryEntry): string => {
  try {
    const { scopes, pii } = entry.grant({} as never);
    const listed = scopes.length === 0 ? 'none' : scopes.map((scope) => `\`${scope}\``).join(', ');
    return `${listed}${pii ? ' (PII)' : ''}${entry.grantDependsOnConfig ? ', by config' : ''}`;
  } catch {
    return 'by config';
  }
};

export function actionsReference(): string {
  const rows = WORKFLOW_ACTIONS.list().map(
    (entry) =>
      `| \`${entry.key}\` | ${String(entry.version)} | ${entry.kind} | ${entry.delivery} | ${entry.adverse} | ${entry.stage} | ${scopesOf(entry)} |`,
  );
  return [
    HEADER('Workflow actions'),
    'Every action version the catalogue serves (`GET /api/v1/workflow-actions`). **Delivery** is what a repeated attempt can do ([delivery](delivery.md)). **Adverse** is whether the step needs the record and the production gates of [automated decisions](../compliance/automated-decisions.md): `by-config` depends on what it names. **Stage** `beta` means the output can carry an H-tier result, and each match then says its method, tier, stage and confidence. An action cannot be undone unless its own object has a way back: no workflow compensates automatically (C119.7).',
    '',
    '| Key | Version | Kind | Delivery | Adverse | Stage | Grant |',
    '|---|---|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}

const codeRows = (types: Readonly<Record<string, string>>): string[] =>
  Object.entries(types)
    .toSorted(([left], [right]) => left.localeCompare(right))
    .map(([code, type]) => `| \`${code}\` | ${type} |`);

