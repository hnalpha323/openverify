/**
 * C277.1 and C277.3 (Workflow 11E, docs-selfhost): `docs/self-hosting/hardening-checklist.md`,
 * generated from the ASVS 5.0.0 Level 2 and MASVS v2.1.0 checklists' rows whose status is
 * `operator` (docs-security's CSVs, C274.1, C275.1). Only ids, our notes, our evidence paths and
 * our threat ids are rendered: never a requirement's or a control's text (both standards are
 * CC BY-SA; rule 15). Deterministic: the checklists' own order, no clock.
 */
import { parse } from 'csv-parse/sync';

/** The page this generator writes. */
export const HARDENING_PAGE = 'docs/self-hosting/hardening-checklist.md';
/** The checklists it reads. */
export const ASVS_CSV = 'docs/security/asvs-5.0.0-l2.csv';
export const MASVS_CSV = 'docs/security/masvs-2.1.0.csv';

/** The status that marks a row only the operator can meet. */
export const OPERATOR_STATUS = 'operator';

/** One checklist row, in C274.1's columns (the MASVS CSV uses the same). */
export interface ChecklistRow {
  readonly id: string;
  readonly level: string;
  readonly status: string;
  readonly evidence: string;
  readonly notes: string;
  readonly threats: string;
}

const COLUMNS = ['id', 'level', 'status', 'evidence', 'notes', 'threats'] as const;

/** A checklist CSV's rows; errors when it does not parse or lacks a column. */
export function parseChecklist(text: string): {
  readonly rows: readonly ChecklistRow[];
  readonly errors: readonly string[];
} {
  let records: Record<string, string>[];
  try {
    records = parse<Record<string, string>>(text, {
      columns: true,
      skip_empty_lines: true,
      relax_column_count: true,
    });
  } catch (error) {
    return {
      rows: [],
      errors: [
        `the checklist does not parse: ${error instanceof Error ? error.message : String(error)}`,
      ],
    };
  }
  const header = text.split('\n', 1)[0] ?? '';
  const present = new Set(header.split(',').map((column) => column.trim()));
  const missing = COLUMNS.filter((column) => !present.has(column));
  if (missing.length > 0) {
    return { rows: [], errors: [`the checklist lacks the columns ${missing.join(', ')}`] };
  }
  return {
    rows: records.map((record) => ({
      id: record.id ?? '',
      level: record.level ?? '',
      status: record.status ?? '',
      evidence: record.evidence ?? '',
      notes: record.notes ?? '',
      threats: record.threats ?? '',
    })),
    errors: [],
  };
}

/** A table cell: one line, pipes escaped. */
function cell(text: string): string {
  const flat = text.replaceAll('\r', '').replaceAll('\n', ' ').replaceAll('|', '\\|').trim();
  return flat === '' ? 'none' : flat;
}

function listOf(text: string, code: boolean): string {
  const items = text
    .split(/[;\s]+/u)
    .map((item) => item.trim())
    .filter((item) => item !== '');
  return items.length === 0
    ? 'none'
    : items.map((item) => (code ? `\`${item}\`` : cell(item))).join(', ');
}

function tableOf(rows: readonly ChecklistRow[], levelHeading: string): string[] {
  const operator = rows.filter((row) => row.status === OPERATOR_STATUS);
  if (operator.length === 0) {
    return [`No row of this checklist has the status \`${OPERATOR_STATUS}\`.`];
  }
  return [
    `| Id | ${levelHeading} | What you do (our note) | Evidence | Threats |`,
    '|---|---|---|---|---|',
    ...operator.map(
      (row) =>
        `| \`${row.id}\` | ${cell(row.level)} | ${cell(row.notes)} | ${listOf(row.evidence, true)} | ${listOf(row.threats, false)} |`,
    ),
  ];
}

function plural(count: number, one: string, many: string): string {
  return `${String(count)} ${count === 1 ? one : many}`;
}

/** The page from the two checklists' rows. */
export function renderHardeningChecklist(
  asvs: readonly ChecklistRow[],
  masvs: readonly ChecklistRow[],
): string {
  const count = (rows: readonly ChecklistRow[]): number =>
    rows.filter((row) => row.status === OPERATOR_STATUS).length;
  return [
    '# Hardening checklist',
    '',
    `<!-- Generated by \`pnpm --filter @openverify/docs-tools docs:selfhost\` from ${ASVS_CSV} and ${MASVS_CSV}. Do not edit: a test fails when this page differs from a fresh render. -->`,
    '',
    `The rows of the project's self-assessed checklists whose status is \`${OPERATOR_STATUS}\`: what OpenVerify cannot do for you and only the operator of an install can (C277.3). ${plural(count(asvs), 'ASVS row', 'ASVS rows')} and ${plural(count(masvs), 'MASVS row', 'MASVS rows')}, read from \`${ASVS_CSV}\` (OWASP ASVS 5.0.0, Level 2) and \`${MASVS_CSV}\` (OWASP MASVS v2.1.0, for the Android SDK's artifacts). Each row gives the requirement's id, never its text: read the requirement in the standard itself. The note is ours, and so is the evidence a reader can follow. A self-assessment is not an audit, and meeting these rows does not make an install meet any standard.`,
    '',
    `The [requirements](requirements.md#what-only-the-operator-can-do-c2773) page lists the same duties by topic; the checklists' other statuses are summarised in \`docs/security/asvs-summary.md\`.`,
    '',
    '## ASVS 5.0.0 Level 2',
    '',
    ...tableOf(asvs, 'Level'),
    '',
    '## MASVS v2.1.0 (the Android SDK)',
    '',
    'A library checklist covers the SDK, not the host app it runs in: the host app keeps its own MASVS duties.',
    '',
    ...tableOf(masvs, 'Group'),
    '',
  ].join('\n');
}
