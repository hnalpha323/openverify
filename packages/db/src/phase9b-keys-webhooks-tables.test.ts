/**
 * Workflow 9B Stage 1b, checkpoint (W): what `foundation-9b` builds in the database for keys, webhooks
 * and notifications (C169.1-C169.7), frozen for `api-keys-webhooks`:
 *
 * - `api_keys.note` (at most 255) and `api_keys.attribute_blocklist` (at most 100 names, `{}` for
 *   every existing key), stored and changed through the key repository;
 * - `webhooks.name` (1 to 200), `description` (at most 1,000), the failure alert as three columns
 *   (`failure_alert_enabled`, `failure_alert_threshold` 1 to 10,000, `failure_alert_window_minutes`
 *   5 to 1,440, all set or none) and `failure_alert_notified_at` (the last alert, at most one per
 *   window), stored and changed through the webhook repository;
 * - `user_notifications`: `case_id` nullable, `webhook_id` beside it with its own composite foreign
 *   key, `subject_type` and `subject_id` derived from them, the kinds of `USER_NOTIFICATION_KINDS`, and
 *   one CHECK per kind holding its subject (`NOTIFICATION_KIND_SUBJECT`; review F18);
 * - `notification_preferences (user_id, kind, console, email, updated_at)`, deleted with the user;
 * - `webhook_alert_emails`, the alert's email outbox (as Phase 8's `case_notification_emails`),
 *   deleted with its webhook and its user.
 *
 * Every value is synthetic.
 */
