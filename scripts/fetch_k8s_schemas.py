#!/usr/bin/env python3
"""Generate the offline Kubernetes JSON schemas kubeconform checks the chart against (C265.3).

For each pinned Kubernetes minor version (1.35, 1.36, 1.37) this script:

1. fetches the release's ``api/openapi-spec/swagger.json`` by tag and kubeconform's own
   ``scripts/openapi2jsonschema.py`` by commit into a cache, each written only after its size and
   SHA-256 match the pin (never a third-party schema archive: those are not byte-stable);
2. expands every definition that names a group, version and kind stand-alone (each
   ``#/definitions/`` reference inlined; a recursive reference becomes an open schema);
3. wraps each kind in a CustomResourceDefinition, the only input the pinned converter reads, and
   runs that converter (it imports PyYAML, so it runs with the ``security/python`` interpreter)
   twice: core kinds named ``{kind}-{version}``, grouped kinds ``{kind}-{group}-{version}``, both
   with the root closed (``DENY_ROOT_ADDITIONAL_PROPERTIES``), which is kubeconform's own layout
   (``{{ .ResourceKind }}{{ .KindSuffix }}.json``) for ``-strict`` checks;
4. writes ``SHA256SUMS`` over the schemas and refuses the bundle unless the SHA-256 of that file
   matches the version's pin, so the bundle is the one reviewed.

Usage, from the repository root::

    python3 -I scripts/fetch_k8s_schemas.py                    # every pinned version
    python3 -I scripts/fetch_k8s_schemas.py --version 1.35     # one version
    python3 -I scripts/fetch_k8s_schemas.py --print-location 1.35
    kubeconform -strict -kubernetes-version 1.35.9 \\
        -schema-location "$(python3 -I scripts/fetch_k8s_schemas.py --print-location 1.35)" ...

The bundle goes to ``data/k8s-schemas/v<version>/`` (gitignored and docker-ignored); it is never
committed. Standard library only.
"""

