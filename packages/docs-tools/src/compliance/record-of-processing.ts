/**
 * C278.5 (checkpoint 3): `docs/compliance/record-of-processing.md`, a record-of-processing template
 * generated from docs-records' data classification ({@link DataClassification}, C276.2) and the
 * recipient list ({@link ProviderFacts}, {@link RECIPIENT_DETAILS}). The software's facts are
 * filled in; every field only the controller can answer is left to fill.
 */
import type {
  ClassEntry,
  DataClassification,
  RetentionDefault,
} from '../records/classification.js';
import { COUNSEL_LINE } from './pages.js';
import type { ProviderFacts } from './provider-facts.js';
import { RECIPIENT_DETAILS } from './recipients.js';

const TO_FILL = '_to fill in_';

const cell = (text: string): string => text.replaceAll('|', '\\|').replaceAll('\n', ' ');

const defaultWords = (value: unknown): string =>
  typeof value === 'number' ? String(value) : 'unset';

const settingWords = (setting: RetentionDefault): string =>
  `\`${setting.key}\` (default ${defaultWords(setting.default)})`;

function classSection(entry: ClassEntry): readonly string[] {
  const profile = entry.profile;
  const categories =
    entry.shareCategories.length === 0
      ? 'none: this class is never shared through Connect'
      : entry.shareCategories.map((category) => `\`${category}\``).join(', ');
  const retention =
    entry.retentionDefaults.length === 0
      ? `no environment setting. ${profile.retention}`
      : `${entry.retentionDefaults.map(settingWords).join(', ')}. ${profile.retention}`;
  return [
    `### \`${entry.id}\`: ${profile.title}`,
    '',
    profile.holds,
    '',
    `- **Sealed columns:** ${String(entry.columns.length)} (kept in plaintext by decision: ${String(entry.plaintext.length)}; each is listed in the [data classification](../security/data-classification.md)).`,
    `- **Encryption at rest:** ${profile.encryption}`,
    `- **Envisaged time limits for erasure:** ${retention}`,
    `- **Access:** ${profile.permission}`,
    `- **Connect share categories:** ${categories}.`,
    `- **Purposes (yours):** ${TO_FILL}`,
    `- **Lawful basis, and the Article 9 condition where it applies (yours):** ${TO_FILL}`,
    `- **Categories of data subjects (yours):** ${TO_FILL}`,
    `- **Recipients (yours):** ${TO_FILL} (the providers you bind, from the table below)`,
    '',
  ];
}

/** Every retention setting the classes name, once, in name order. */
function retentionSettings(classification: DataClassification): readonly RetentionDefault[] {
  const byKey = new Map<string, RetentionDefault>();
  for (const entry of classification.classes) {
    for (const setting of entry.retentionDefaults) {
      byKey.set(setting.key, setting);
    }
  }
  return [...byKey.values()].sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
}

/** The template's text for a classification and a provider registry. */
export function renderRecordOfProcessing(
  classification: DataClassification,
  facts: ProviderFacts,
): string {
  const names = Object.keys(RECIPIENT_DETAILS).sort();
  const kindsOf = (name: string): string =>
    facts.kinds
      .filter((kind) => (facts.namesByKind[kind] ?? []).includes(name))
      .map((kind) => `\`${kind}\``)
      .join(', ');
  const boundWhenUnset = facts.kinds.filter((kind) => {
    const value = facts.unsetDefaults[kind];
    return value !== null && value !== undefined;
  });
  const recipientRows = names.map((name) => {
    const detail = RECIPIENT_DETAILS[name];
    if (detail === undefined) {
      throw new Error(`no recipient detail for the provider name ${name}`);
    }
    return `| \`${name}\` | ${kindsOf(name)} | ${cell(detail.recipient)} | ${cell(detail.receives)} | ${TO_FILL} |`;
  });
  const retentionRows = retentionSettings(classification).map(
    (setting) => `| \`${setting.key}\` | ${defaultWords(setting.default)} | ${TO_FILL} |`,
  );

  return [
    '# Record of processing (template)',
    '',
    'This is not legal advice.',
    '',
    COUNSEL_LINE,
    '',
    "Generated by `pnpm --filter @openverify/docs-tools docs:compliance` from the [data classification](../security/data-classification.md) (itself generated from the code, C276.2) and the provider registry (`apps/api/src/providers/index.ts`); do not edit it by hand, and a test fails when it and a fresh render differ (C278.5). Copy it into your own record: the software's side is filled in, and every field marked _to fill in_ is yours.",
    '',
    "What a record holds: under the UK GDPR's Article 30(1) (re-read on 2026-11-20, [sources](sources.md)), the controller's name and contact details (and any joint controller, representative and data protection officer), the purposes, the categories of data subjects and of personal data, the categories of recipients, transfers to a third country or international organisation, where possible the time limits for erasure, and where possible a general description of the security measures; a processor keeps its own record under Article 30(2). The exemption for organisations under 250 people does not apply where processing includes special-category data, which biometric verification usually does. The EU's Article 30 was not re-read on 2026-11-20 (EUR-Lex returned no text).",
    '',
    '## The controller',
    '',
    '| Item | Yours |',
    '|---|---|',
    `| Controller and contact details | ${TO_FILL} |`,
    `| Joint controller, representative, data protection officer | ${TO_FILL} |`,
    `| Purposes of the processing | ${TO_FILL} (one per activity: onboarding, fraud prevention, age checks, sharing) |`,
    `| Categories of data subjects | ${TO_FILL} (for example applicants, account holders, people on your lists, your own staff) |`,
    `| Transfers to a third country or international organisation | ${TO_FILL} (bound providers outside your jurisdiction; Connect shares, [sharing](sharing.md)) |`,
    `| Security measures | The software's, below, and yours |`,
    '',
    '## Categories of personal data, by class',
    '',
    `The classes of the data classification, ${String(classification.classes.length)} in all, with what the software does for each.`,
    '',
    ...classification.classes.flatMap(classSection),
    '## Recipients the software can send to',
    '',
    `Every real adapter of the provider registry. Each is unbound until you bind it, except ${boundWhenUnset.map((kind) => `\`${kind}\``).join(' and ')}, which an unset variable binds ([recipients](recipients.md) has the variables, and the egress that is not a provider: email, webhooks, workflow HTTPS requests, Connect).`,
    '',
    '| Provider | Kind | Recipient | What it receives | Bound in your install (yours) |',
    '|---|---|---|---|---|',
    ...recipientRows,
    '',
    '## Envisaged time limits for erasure',
    '',
    'The retention settings the classes name, with the defaults the contracts hold ([retention](retention.md) has every one and what it removes).',
    '',
    '| Setting | Default | Your value |',
    '|---|---|---|',
    ...retentionRows,
    '',
    '## Security measures',
    '',
    "The software's measures are described in the [crypto inventory](../security/crypto-inventory.md), the [data classification](../security/data-classification.md), the [logging inventory](../security/logging.md), the [threat model](../security/threat-model.md) and the self-assessed [ASVS summary](../security/asvs-summary.md); the [hardening checklist](../self-hosting/hardening-checklist.md) lists what the operator configures. Your own measures (access management, staff, hosting) are yours to add.",
    '',
  ].join('\n');
}
