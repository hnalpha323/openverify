/** The backticked spans of a text. */
function codeSpans(text: string): readonly string[] {
  const spans: string[] = [];
  let at = text.indexOf('`');
  while (at >= 0) {
    const end = text.indexOf('`', at + 1);
    if (end < 0) break;
    spans.push(text.slice(at + 1, end));
    at = text.indexOf('`', end + 1);
  }
  return spans;
}

/** The relative link targets of a Markdown text (no scheme, no pure anchor), without anchors. */
function relativeLinks(text: string): readonly string[] {
  const links: string[] = [];
  for (let at = text.indexOf(']('); at >= 0; at = text.indexOf('](', at + 2)) {
    const end = text.indexOf(')', at + 2);
    const target = end < 0 ? '' : (text.slice(at + 2, end).split('#')[0] ?? '');
    if (target !== '' && !target.includes('://') && !target.startsWith('mailto:')) {
      links.push(target);
    }
  }
  return links;
}

/** `target` resolved against the page's directory, as a repository-relative path. */
function resolve(page: string, target: string): string {
  const parts = page.split('/').slice(0, -1);
  for (const part of target.split('/')) {
    if (part === '..') parts.pop();
    else if (part !== '.' && part !== '') parts.push(part);
  }
  return parts.join('/');
}

const EVENT = /^(?:connect\/[a-z-]+\.[a-z-]+|consent-record\.[a-z-]+)$/;
const SCOPE = /^connect-[a-z-]+:[a-z]+$/;
const VARIABLE = /\bOPENVERIFY_[A-Z0-9_]+\b/g;
const REPOSITORY_PATH =
  /^(?:apps|packages|docs|contracts|android|services|infra|deploy)\/[\w./-]+$/;

/** Every record rule over the guide's pages. */
export const connectGuideFindings: (repo: Repository) => readonly CheckFinding[] = (repo) => {
  const events = new Set<string>(EVENT_NAMES);
  const permissions = new Set<string>(PERMISSIONS);
  const variables = new Set(CONFIG_REGISTRY.map((entry) => entry.name));
  const prefixes = CONFIG_REGISTRY.flatMap((entry) =>
    'prefix' in entry && typeof entry.prefix === 'string' ? [entry.prefix] : [],
  );
  return CONNECT_GUIDE_PAGES.flatMap((page): CheckFinding[] => {
    const finding = (message: string): CheckFinding => ({
      rule: 'catalog-connect-guide',
      path: page,
      message: `${page} ${message}`,
      severity: 'error',
    });
    if (!repo.exists(page)) {
      return [finding('does not exist')];
    }
    const text = repo.readText(page);
    if (text.includes(DRAFT_MARKER_PREFIX)) {
      return [finding('is still a stub')];
    }
    const spans = codeSpans(text);
    const lower = text.toLowerCase();
    return [
      ...spans
        .filter((span) => EVENT.test(span) && !events.has(span) && !NOT_EMITTED.includes(span))
        .map((span) => finding(`names an unknown event ${span}`)),
      ...spans
        .filter((span) => SCOPE.test(span) && !permissions.has(span))
        .map((span) => finding(`names an unknown scope ${span}`)),
      ...[...new Set(text.match(VARIABLE) ?? [])]
        .filter(
          (name) => !variables.has(name) && !prefixes.some((prefix) => name.startsWith(prefix)),
        )
        .map((name) => finding(`names an unknown variable ${name}`)),
      ...relativeLinks(text)
        .filter((target) => !repo.exists(resolve(page, target)))
        .map((target) => finding(`links ${target}, which does not exist`)),
      ...spans
        .filter((span) => REPOSITORY_PATH.test(span) && !span.includes('<'))
        .filter((span) => !repo.exists(span) && repo.listFiles(span).length === 0)
        .map((span) => finding(`cites ${span}, which does not exist`)),
      ...text
        .split('**Ours**')
        .slice(1)
        .filter((after) => !after.startsWith(' (reason: '))
        .map(() => finding('has an "Ours" label without its reason')),
      ...(REQUIRED[page] ?? [])
        .filter((statement) => !lower.includes(statement.toLowerCase()))
        .map((statement) =>
          finding(
            page.endsWith('consent.md') && statement === 'not legal advice'
              ? 'does not say "not legal advice"'
              : `does not state "${statement}"`,
          ),
        ),
    ];
  });
};
