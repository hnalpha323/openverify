// :openverify-sdk:generateLocaleStrings (C199.1; reviews V07, F08, H16), owned by android-i18n.
//
// Writes the generated strings_catalog.xml of the five SDK locale folders, and no other file, from
// i18n/key-map.json and the web catalogs contracts/fixtures/i18n/<locale>.json (Phase 9's export):
// every key-mapped SDK string, the consent and notice texts among them, in the web's own words for
// its catalogKey, in the key map's order. The words are never drafted here and never fall back to
// another locale: a catalog key missing from a locale, a text that is not one string, or a text that
// is not NFC (C200.2) fails the task. The web's {{name}} placeholders stay as they are written; the
// screen that shows a text fills them by name (the consent screen fills {{days}}).
//
// Run it after a key-map entry or a web catalog changes, and commit what it writes in the same
// commit: (cd android && ./gradlew --no-daemon :openverify-sdk:generateLocaleStrings). KeyMapCatalogTest
// fails when a committed catalog differs from the web's words.
//
// Applied by the generateLocaleStrings task that foundation-10a registers in build.gradle.kts. The
// action reads only the files and maps captured below, so the configuration cache can store it.

import groovy.json.JsonSlurper
import java.text.Normalizer

/** Each SDK locale (the web catalog's name) with its folder under composeResources and its name in English. */
val sdkLocales: List<Triple<String, String, String>> = listOf(
    Triple("en", "values", "English"),
    Triple("es", "values-es", "Spanish"),
    Triple("fr", "values-fr", "French"),
    Triple("de", "values-de", "German"),
    Triple("ar", "values-ar", "Arabic"),
)

val keyMapFile: File = file("i18n/key-map.json")
val webCatalogs: Map<String, File> = sdkLocales.associate { (locale, _, _) -> locale to rootProject.file("../contracts/fixtures/i18n/$locale.json") }
val catalogFiles: Map<String, File> = sdkLocales.associate { (locale, folder, _) -> locale to file("src/commonMain/composeResources/$folder/strings_catalog.xml") }
val localeNames: Map<String, String> = sdkLocales.associate { (locale, _, name) -> locale to name }

// Configured lazily by name, so the order of the task's registration and this script's application
// does not matter.
tasks.matching { it.name == "generateLocaleStrings" }.configureEach {
    group = "openverify"
    description = "Writes strings_catalog.xml in the five SDK locale folders from the key map and the web catalogs (C199.1)."
    val keyMap = keyMapFile
    val catalogs = webCatalogs
    val outputFiles = catalogFiles
    val names = localeNames
    inputs.file(keyMap)
    inputs.files(catalogs.values)
    outputs.files(outputFiles.values)
    doLast {
        /** Each mapped resource with the dotted catalog key its words come from, in the key map's order. */
        val mapped: List<Pair<String, String>> = ((JsonSlurper().parse(keyMap) as Map<*, *>)["entries"] as List<*>).map { entry ->
            val fields = entry as Map<*, *>
            (fields["resource"] as String) to (fields["catalogKey"] as String)
        }

        /** The text of [key] in [locale]'s web catalog: one NFC string, or the task fails naming the locale and key. */
        fun catalogText(locale: String, messages: Any?, key: String): String {
            val text = key.split('.').fold(messages) { node, part -> (node as? Map<*, *>)?.get(part) }
            if (text !is String) throw GradleException("generateLocaleStrings: $locale has no text for $key")
            if (!Normalizer.isNormalized(text, Normalizer.Form.NFC)) throw GradleException("generateLocaleStrings: $locale $key is not NFC")
            return text
        }

        /** [text] as a Compose resource text: XML's escapes and the backslash, line feed and tab escapes Compose reads. */
        fun resourceText(text: String): String = buildString {
            for (character in text) {
                when (character) {
                    '&' -> append("&amp;")
                    '<' -> append("&lt;")
                    '>' -> append("&gt;")
                    '\\' -> append("\\\\")
                    '\n' -> append("\\n")
                    '\t' -> append("\\t")
                    else -> append(character)
                }
            }
        }

        for ((locale, output) in outputFiles) {
            val messages = (JsonSlurper().parse(catalogs.getValue(locale)) as Map<*, *>)["messages"]
            val xml = buildString {
                append("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n")
                append("<!--\n")
                append("  GENERATED by :openverify-sdk:generateLocaleStrings (scripts/generate-locale-strings.gradle.kts):\n")
                append("  the SDK strings that i18n/key-map.json maps to a web catalog key (C199.1), in the ${names.getValue(locale)}\n")
                append("  words of contracts/fixtures/i18n/$locale.json. Never edit this file by hand, and never define one of\n")
                append("  these strings in another file (KeyMapCatalogTest): change the key map or the web catalog, then run\n")
                append("  the task. The consent and notice texts are recorded by key with the user's consent; {{days}} is the\n")
                append("  session's face-template-retention-days, filled by the consent screen.\n")
                append("-->\n")
                append("<resources>\n")
                for ((resource, key) in mapped) {
                    append("    <string name=\"").append(resource).append("\">")
                    append(resourceText(catalogText(locale, messages, key)))
                    append("</string>\n")
                }
                append("</resources>\n")
            }
            output.parentFile.mkdirs()
            if (!output.isFile || output.readText() != xml) output.writeText(xml)
        }
    }
}
