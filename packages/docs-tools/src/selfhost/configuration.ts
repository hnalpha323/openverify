/**
 * C277.2 (Workflow 11E, docs-selfhost): `docs/self-hosting/configuration.md`, generated from
 * `apps/api/src/config-registry.ts` (foundation-11b's registry, extended by 11C): every variable
 * with its description, default, secret flag, `<NAME>_FILE` form (C249.2) and the processes that
 * read it, the pattern entries rendered as patterns. The registry imports nothing, so a relative
 * import keeps `tsc` to that one file. Deterministic: sorted by name, no clock, no host.
 */
import {
  CONFIG_PROCESSES,
  CONFIG_REGISTRY,
  isPatternEntry,
  type ConfigProcess,
  type ConfigVariable,
} from '../../../../apps/api/src/config-registry.js';

/** The page this generator writes. */
export const CONFIGURATION_PAGE = 'docs/self-hosting/configuration.md';

/** What each process of C277.2 is, for the reader (the registry names them only). */
const PROCESS_ROLES: Readonly<Record<ConfigProcess, string>> = Object.freeze({
  api: 'The REST API server (`apps/api`, image `openverify/api`, `node dist/server.js`).',
  worker: 'The job worker (`apps/api`, the same image, `node dist/worker.js`).',
  migrate:
    '`db:migrate`, `db:grant-runtime` and the operator commands (`apps/api`, the same image).',
  dashboard: 'The operator console (`apps/dashboard`, image `openverify/dashboard`).',
  flow: 'The hosted flow and its server (`apps/flow`, image `openverify/flow`).',
  vision: 'The vision service (`services/vision`, image `openverify/vision`).',
  'code-runner':
    "Evaluate Code's runner pool (`packages/workflow-engine/bin`, image `openverify/code-runner`).",
});

/** A table cell: one line, pipes escaped. */
function cell(text: string): string {
  return text.replaceAll('\r', '').replaceAll('\n', ' ').replaceAll('|', '\\|');
}

const code = (text: string): string => `\`${text}\``;

function byName(a: ConfigVariable, b: ConfigVariable): number {
  return a.name < b.name ? -1 : a.name > b.name ? 1 : 0;
}

/** The processes of `entry`, in the registry's process order. */
function processesOf(entry: ConfigVariable): string {
  return CONFIG_PROCESSES.filter((process) => entry.processes.includes(process)).join(', ');
}

function defaultOf(entry: ConfigVariable): string {
  return entry.default === null ? 'unset' : code(cell(entry.default));
}

function fileFormOf(entry: ConfigVariable): string {
  return entry.fileForm ? code(`${entry.name}_FILE`) : 'none';
}

const yesNo = (value: boolean): string => (value ? 'yes' : 'no');

function plural(count: number, one: string, many: string): string {
  return `${count.toLocaleString('en-US')} ${count === 1 ? one : many}`;
}

/** Renders the configuration reference for `registry` (the real registry by default). */
export function renderConfigurationReference(
  registry: readonly ConfigVariable[] = CONFIG_REGISTRY,
): string {
  const entries = [...registry].sort(byName);
  const exact = entries.filter((entry) => !isPatternEntry(entry));
  const patterns = entries.filter(isPatternEntry);
  const secrets = entries.filter((entry) => entry.secret);

  const lines: string[] = [
    '# Configuration reference',
    '',
    '<!-- Generated by `pnpm --filter @openverify/docs-tools docs:selfhost` from apps/api/src/config-registry.ts. Do not edit: a test fails when this page differs from a fresh render. -->',
    '',
    `Every environment variable an OpenVerify process reads (C277.2), generated from \`apps/api/src/config-registry.ts\`: ${plural(entries.length, 'entry', 'entries')}: ${plural(exact.length, 'name', 'names')} and ${plural(patterns.length, 'pattern', 'patterns')}, ${plural(secrets.length, 'secret', 'secrets')} among them. The registry is the source; this page is never edited by hand. \`apps/api/src/config-registry.test.ts\` fails when a process's sources read a name the registry does not hold, and \`packages/docs-tools/src/selfhost/configuration.test.ts\` fails when this page differs from a fresh render (\`pnpm --filter @openverify/docs-tools docs:selfhost\` writes it).`,
    '',
    'How to read the tables:',
    '',
    '- **Default**: the value a process uses when the variable is unset; `unset` means the feature is off, the setting has no value, or the variable is required (the description says which).',
    '- **Secret**: never logged; a `change-me` placeholder is refused in production mode. Where each secret lives and how it rotates is in [secrets-and-rotation.md](secrets-and-rotation.md) and `docs/security/crypto-inventory.md`, never a value.',
    '- **`_FILE` form**: the process also reads the value from the file that `<NAME>_FILE` names, a path to a mounted secret (C249.2; `apps/api/src/config/secret-files.ts` for the API, the worker and the commands, and the same rules in the console, the flow server, vision and the code runner). The trailing newline is trimmed, setting both forms stops the start, and a world-readable file is a warning (a group-readable one is not, which is how a Kubernetes secret mounted `0440` with `fsGroup` is read).',
    '- **Processes**: which of the seven processes read the name. A process ignores the names it does not read.',
    '',
    '## Processes',
    '',
    '| Process | What it is | Names it reads | Secrets |',
    '|---|---|---|---|',
    ...CONFIG_PROCESSES.map((process) => {
      const read = entries.filter((entry) => entry.processes.includes(process));
      const secret = read.filter((entry) => entry.secret);
      return `| ${code(process)} | ${PROCESS_ROLES[process]} | ${String(read.length)} | ${String(secret.length)} |`;
    }),
    '',
    '## Variables',
    '',
    '| Name | Description | Default | Secret | `_FILE` form | Processes |',
    '|---|---|---|---|---|---|',
    ...exact.map(
      (entry) =>
        `| ${code(entry.name)} | ${cell(entry.description)} | ${defaultOf(entry)} | ${yesNo(entry.secret)} | ${fileFormOf(entry)} | ${processesOf(entry)} |`,
    ),
    '',
    '## Names composed at run time',
    '',
    'A pattern entry stands for every name a process composes from its fixed start and the parts in braces (for example a provider kind and an environment kind). Its `_FILE` form is the composed name with `_FILE` appended.',
    '',
    '| Pattern | Fixed start | Description | Default | Secret | `_FILE` form | Processes |',
    '|---|---|---|---|---|---|---|',
    ...patterns.map(
      (entry) =>
        `| ${code(entry.name)} | ${code(entry.prefix ?? '')} | ${cell(entry.description)} | ${defaultOf(entry)} | ${yesNo(entry.secret)} | ${fileFormOf(entry)} | ${processesOf(entry)} |`,
    ),
    '',
  ];
  return lines.join('\n');
}
