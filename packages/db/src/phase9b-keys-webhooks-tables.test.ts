describe('api_keys.note and api_keys.attribute_blocklist (C169.1, C169.3)', () => {
  it('are a nullable note and a blocklist that is empty unless set', async () => {
    const { environment } = await createTestTenant(database.db);
    const key = await newKey(environment.id);

    expect(await column('api_keys', 'note')).toEqual({
      column_name: 'note',
      data_type: 'text',
      is_nullable: 'YES',
    });
    expect(await column('api_keys', 'attribute_blocklist')).toEqual({
      column_name: 'attribute_blocklist',
      data_type: 'ARRAY',
      is_nullable: 'NO',
    });
    const { rows } = await query<{ note: string | null; attribute_blocklist: string[] }>(
      'select note, attribute_blocklist from api_keys where id = $1',
      [key.id],
    );
    expect(rows).toEqual([{ note: null, attribute_blocklist: [] }]);
  });

  it('hold a note of at most 255 characters and at most 100 blocked names', async () => {
    const { environment } = await createTestTenant(database.db);
    const key = await newKey(environment.id);

    expect(
      await refused('update api_keys set note = $1 where id = $2', ['n'.repeat(256), key.id]),
    ).toContain('api_keys_note_length');
    expect(
      await refused('update api_keys set attribute_blocklist = $1 where id = $2', [
        Array.from({ length: 101 }, (_, index) => `name-${String(index)}`),
        key.id,
      ]),
    ).toContain('api_keys_attribute_blocklist_size');
    expect(
      await refused('update api_keys set note = $1 where id = $2', ['n'.repeat(255), key.id]),
    ).toBe('accepted');
  });

  it('are stored on create and changed on update through the key repository', async () => {
    const { environment } = await createTestTenant(database.db);
    const key = await newKey(environment.id, {
      note: 'Synthetic reconciliation job',
      attributeBlocklist: ['address-street-1', 'birthdate'],
    });
    const read = async () =>
      (
        await query<{ note: string | null; attribute_blocklist: string[] }>(
          'select note, attribute_blocklist from api_keys where id = $1',
          [key.id],
        )
      ).rows;

    expect(await read()).toEqual([
      {
        note: 'Synthetic reconciliation job',
        attribute_blocklist: ['address-street-1', 'birthdate'],
      },
    ]);
    // A variable naming a member the changes already had, so it reaches the repository as declared.
    const cleared = { name: 'Synthetic backend', note: null, attributeBlocklist: [] };
    await updateApiKey(database.db, environment.id, key.id, cleared);
    expect(await read()).toEqual([{ note: null, attribute_blocklist: [] }]);
  });
});

describe('webhooks: name, description and the failure alert (C169.5, C169.6)', () => {
  it('are nullable columns, and an existing webhook has none of them', async () => {
    const { environment } = await createTestTenant(database.db);
    const webhook = await newWebhook(environment.id);

    for (const [name, type] of [
      ['name', 'text'],
      ['description', 'text'],
      ['failure_alert_enabled', 'boolean'],
      ['failure_alert_threshold', 'integer'],
      ['failure_alert_window_minutes', 'integer'],
      ['failure_alert_notified_at', 'timestamp with time zone'],
    ] as const) {
      expect(await column('webhooks', name), name).toEqual({
        column_name: name,
        data_type: type,
        is_nullable: 'YES',
      });
    }
    const { rows } = await query(
      `select name, description, failure_alert_enabled, failure_alert_threshold,
              failure_alert_window_minutes, failure_alert_notified_at
         from webhooks where id = $1`,
      [webhook.id],
    );
    expect(rows).toEqual([
      {
        name: null,
        description: null,
        failure_alert_enabled: null,
        failure_alert_threshold: null,
        failure_alert_window_minutes: null,
        failure_alert_notified_at: null,
      },
    ]);
  });

  it('hold a name of 1 to 200, a description of at most 1,000 and an alert set whole, in its bounds', async () => {
    const { environment } = await createTestTenant(database.db);
    const { id } = await newWebhook(environment.id);
    const set = (assignments: string, params: unknown[]) =>
      refused(`update webhooks set ${assignments} where id = $1`, [id, ...params]);

    expect(await set('name = $2', [''])).toContain('webhooks_name_length');
    expect(await set('name = $2', ['n'.repeat(201)])).toContain('webhooks_name_length');
    expect(await set('description = $2', ['d'.repeat(1001)])).toContain(
      'webhooks_description_length',
    );
    expect(await set('failure_alert_enabled = true', [])).toContain('webhooks_failure_alert_whole');
    const alert = (threshold: number, minutes: number) =>
      set(
        'failure_alert_enabled = true, failure_alert_threshold = $2, failure_alert_window_minutes = $3',
        [threshold, minutes],
      );
    expect(await alert(0, 60)).toContain('webhooks_failure_alert_threshold_range');
    expect(await alert(10_001, 60)).toContain('webhooks_failure_alert_threshold_range');
    expect(await alert(5, 4)).toContain('webhooks_failure_alert_window_range');
    expect(await alert(5, 1441)).toContain('webhooks_failure_alert_window_range');
    expect(await alert(10_000, 1440)).toBe('accepted');
    expect(await set('name = $2, description = $3', ['n'.repeat(200), 'd'.repeat(1000)])).toBe(
      'accepted',
    );
  });

  it('are stored on create and changed on update through the webhook repository', async () => {
    const { environment } = await createTestTenant(database.db);
    const webhook = await newWebhook(environment.id, {
      name: 'Synthetic CRM sync',
      description: 'Sends completed inquiries to the synthetic CRM.',
      failureAlert: { enabled: true, threshold: 5, windowMinutes: 30 },
    });
    const read = async () =>
      (
        await query(
          `select name, description, failure_alert_enabled, failure_alert_threshold,
                  failure_alert_window_minutes from webhooks where id = $1`,
          [webhook.id],
        )
      ).rows;

    expect(await read()).toEqual([
      {
        name: 'Synthetic CRM sync',
        description: 'Sends completed inquiries to the synthetic CRM.',
        failure_alert_enabled: true,
        failure_alert_threshold: 5,
        failure_alert_window_minutes: 30,
      },
    ]);
    const changes = {
      url: 'https://hooks.example.test/openverify',
      name: null,
      description: null,
      failureAlert: null,
    };
    await updateWebhook(database.db, environment.id, webhook.id, changes);
    expect(await read()).toEqual([
      {
        name: null,
        description: null,
        failure_alert_enabled: null,
        failure_alert_threshold: null,
        failure_alert_window_minutes: null,
      },
    ]);
  });
});

describe('user_notifications: the polymorphic subject (C169.7, review F18)', () => {
  async function caseOf(environmentId: string) {
    const template = await seedCaseTemplate(database.db, environmentId);
    return seedCase(database.db, environmentId, {
      caseTemplateId: template.id,
      caseTemplateVersionId: template.versionId,
      key: template.key,
      number: 1,
    });
  }

  const insert = (
    environmentId: string,
    userId: string,
    kind: string,
    caseId: string | null,
    webhookId: string | null,
  ) =>
    refused(
      `insert into user_notifications (id, environment_id, user_id, kind, case_id, webhook_id)
       values ($1, $2, $3, $4, $5, $6)`,
      [testId('unot'), environmentId, userId, kind, caseId, webhookId],
    );

  it('makes case_id nullable and adds webhook_id, with the subject derived from them', async () => {
    expect(await column('user_notifications', 'case_id')).toEqual({
      column_name: 'case_id',
      data_type: 'text',
      is_nullable: 'YES',
    });
    for (const name of ['webhook_id']) {
      expect(await column('user_notifications', name), name).toEqual({
        column_name: name,
        data_type: 'text',
        is_nullable: 'YES',
      });
    }
    for (const name of ['subject_type', 'subject_id']) {
      expect(await column('user_notifications', name), name).toEqual({
        column_name: name,
        data_type: 'text',
        is_nullable: 'NO',
      });
    }
    const { rows } = await query<{ column_name: string; is_generated: string }>(
      `select column_name, is_generated from information_schema.columns
        where table_name = 'user_notifications' and column_name in ('subject_type', 'subject_id')
        order by column_name`,
    );
    expect(rows).toEqual([
      { column_name: 'subject_id', is_generated: 'ALWAYS' },
      { column_name: 'subject_type', is_generated: 'ALWAYS' },
    ]);
  });

  it('keeps a case kind about its case, read as subject case', async () => {
    const { environment, user } = await tenantWithUser();
    const found = await caseOf(environment.id);
    const [row] = await createUserNotifications(database.db, environment.id, [
      { id: testId('unot'), userId: user.id, kind: 'assigned', caseId: found.id },
    ]);

    const { rows } = await query(
      'select subject_type, subject_id, case_id, webhook_id from user_notifications where id = $1',
      [row?.id],
    );
    expect(rows).toEqual([
      { subject_type: 'case', subject_id: found.id, case_id: found.id, webhook_id: null },
    ]);
  });

  it('writes a webhook failure about its webhook, read as subject webhook, through the repository', async () => {
    const { environment, user } = await tenantWithUser();
    const webhook = await newWebhook(environment.id);
    const id = testId('unot');

    await createWebhookFailureNotifications(database.db, environment.id, [
      { id, userId: user.id, webhookId: webhook.id },
    ]);

    const { rows } = await query(
      `select kind, subject_type, subject_id, case_id, webhook_id, read_at
         from user_notifications where id = $1`,
      [id],
    );
    expect(rows).toEqual([
      {
        kind: 'webhook-failure',
        subject_type: 'webhook',
        subject_id: webhook.id,
        case_id: null,
        webhook_id: webhook.id,
        read_at: null,
      },
    ]);
  });

  it('holds every kind of USER_NOTIFICATION_KINDS to its subject, one CHECK per kind', async () => {
    const { environment, user } = await tenantWithUser();
    const found = await caseOf(environment.id);
    const webhook = await newWebhook(environment.id);

    expect(await insert(environment.id, user.id, 'archived', found.id, null)).toContain(
      'user_notifications_kind_valid',
    );
    for (const kind of USER_NOTIFICATION_KINDS) {
      const constraint = `user_notifications_${kind.replaceAll('-', '_')}_subject`;
      const subject = NOTIFICATION_KIND_SUBJECT[kind];
      const own = subject === 'case' ? [found.id, null] : [null, webhook.id];
      const other = subject === 'case' ? [null, webhook.id] : [found.id, null];
      // No subject at all is refused first by the derived subject_id's NOT NULL.
      expect(await insert(environment.id, user.id, kind, null, null), kind).toContain(
        'null value in column "subject_id"',
      );
      expect(
        await insert(environment.id, user.id, kind, other[0] ?? null, other[1] ?? null),
        kind,
      ).toContain(constraint);
      expect(await insert(environment.id, user.id, kind, found.id, webhook.id), kind).toContain(
        constraint,
      );
      expect(
        await insert(environment.id, user.id, kind, own[0] ?? null, own[1] ?? null),
        kind,
      ).toBe('accepted');
    }
  });

  it('refuses another environment’s webhook, and goes with its webhook', async () => {
    const { environment, user } = await tenantWithUser();
    const other = await createTestTenant(database.db);
    const foreign = await newWebhook(other.environment.id);
    const webhook = await newWebhook(environment.id);

    expect(await insert(environment.id, user.id, 'webhook-failure', null, foreign.id)).toContain(
      'user_notifications_webhook_fk',
    );
    expect(await insert(environment.id, user.id, 'webhook-failure', null, webhook.id)).toBe(
      'accepted',
    );
    await query('delete from webhooks where id = $1', [webhook.id]);
    const { rows } = await query<{ count: number }>(
      'select count(*)::int as count from user_notifications where webhook_id = $1',
      [webhook.id],
    );
    expect(rows).toEqual([{ count: 0 }]);
  });
});

describe('notification_preferences (C169.7)', () => {
  it('holds one row per user and kind, for the kinds of USER_NOTIFICATION_KINDS', async () => {
    const { user } = await tenantWithUser();

    expect((await columnsOf('notification_preferences')).map((row) => row.column_name)).toEqual([
      'console',
      'email',
      'kind',
      'updated_at',
      'user_id',
    ]);
    expect(
      await refused(
        `insert into notification_preferences (user_id, kind, console, email) values ($1, 'archived', true, false)`,
        [user.id],
      ),
    ).toContain('notification_preferences_kind_valid');
    const insert = () =>
      refused(
        `insert into notification_preferences (user_id, kind, console, email) values ($1, 'assigned', true, false)`,
        [user.id],
      );
    expect(await insert()).toBe('accepted');
    expect(await insert()).toContain('notification_preferences_pkey');
  });

  it('are read and set through the repository, keeping the kinds a change does not name', async () => {
    const { user } = await tenantWithUser();
    const at = new Date('2026-11-06T10:00:00.000Z');

    expect(await listNotificationPreferences(database.db, user.id)).toEqual([]);
    await setNotificationPreferences(
      database.db,
      user.id,
      {
        'webhook-failure': { console: true, email: true },
        assigned: { console: false, email: false },
      },
      at,
    );
    const later = new Date('2026-11-06T11:00:00.000Z');
    await setNotificationPreferences(
      database.db,
      user.id,
      { assigned: { console: true, email: false } },
      later,
    );

    expect(await listNotificationPreferences(database.db, user.id)).toEqual([
      { kind: 'assigned', console: true, email: false, updatedAt: later },
      { kind: 'webhook-failure', console: true, email: true, updatedAt: at },
    ]);
  });

  it('go with their user', async () => {
    const { user } = await tenantWithUser();
    await setNotificationPreferences(
      database.db,
      user.id,
      { mentioned: { console: true, email: true } },
      new Date('2026-11-06T10:00:00.000Z'),
    );

    await query('delete from users where id = $1', [user.id]);

    expect(await listNotificationPreferences(database.db, user.id)).toEqual([]);
  });
});

describe('webhook_alert_emails, the failure alert’s outbox (C169.6; outcome 21)', () => {
  const queue = (environmentId: string, userId: string, webhookId: string) =>
    refused(
      `insert into webhook_alert_emails (environment_id, user_id, webhook_id) values ($1, $2, $3)`,
      [environmentId, userId, webhookId],
    );

  it('holds a user and a webhook of its environment, with at most 3 claimed attempts', async () => {
    const { environment, user } = await tenantWithUser();
    const webhook = await newWebhook(environment.id);
    const other = await createTestTenant(database.db);
    const foreign = await newWebhook(other.environment.id);

    expect((await columnsOf('webhook_alert_emails')).map((row) => row.column_name)).toEqual([
      'attempts',
      'claimed_at',
      'created_at',
      'environment_id',
      'id',
      'user_id',
      'webhook_id',
    ]);
    expect(await queue(environment.id, user.id, foreign.id)).toContain(
      'webhook_alert_emails_webhook_fk',
    );
    expect(await queue(environment.id, user.id, webhook.id)).toBe('accepted');
    expect(
      await refused(`update webhook_alert_emails set attempts = 1 where webhook_id = $1`, [
        webhook.id,
      ]),
    ).toContain('webhook_alert_emails_attempts_range');
    expect(
      await refused(
        `update webhook_alert_emails set attempts = 4, claimed_at = now() where webhook_id = $1`,
        [webhook.id],
      ),
    ).toContain('webhook_alert_emails_attempts_range');
  });

  it('goes with its webhook and with its user', async () => {
    const { environment, user } = await tenantWithUser();
    const first = await newWebhook(environment.id);
    const second = await newWebhook(environment.id);
    await queue(environment.id, user.id, first.id);
    await queue(environment.id, user.id, second.id);
    const count = async () =>
      (
        await query<{ count: number }>(
          'select count(*)::int as count from webhook_alert_emails where user_id = $1',
          [user.id],
        )
      ).rows;

    await query('delete from webhooks where id = $1', [first.id]);
    expect(await count()).toEqual([{ count: 1 }]);
    await query('delete from users where id = $1', [user.id]);
    expect(await count()).toEqual([{ count: 0 }]);
  });
});
