import { randomBytes } from 'node:crypto';
import { sql } from 'drizzle-orm';
import { afterAll, beforeAll, describe, expect, it, onTestFinished } from 'vitest';
import { InvalidCursorError } from '../errors.js';
import {
  createdAtClock,
  createTestDatabase,
  createTestTenant,
  testId,
  type TestDatabase,
  wallClockStepsBack,
} from '../testing.js';
import { createEvent } from './events.js';
import {
  createWebhook,
  createWebhookDelivery,
  getWebhook,
  getWebhookDelivery,
  getWebhookSigningSecret,
  listDueWebhookDeliveries,
  listWebhooks,
  listWebhooksForEvent,
  recordWebhookDeliveryAttempt,
  updateWebhook,
  type EventSubject,
} from './webhooks.js';
import type { WebhookFilters } from '../schema.js';

let database: TestDatabase;

beforeAll(async () => {
  database = await createTestDatabase();
});

afterAll(async () => {
  await database.close();
});

// Synthetic signing secret generated per run; real ones are generated by the API.
const SECRET = `wbhsec_${randomBytes(24).toString('base64url')}`;
const LAST4 = SECRET.slice(-4);

const newWebhook = (environmentId: string, enabledEvents = ['inquiry.completed']) =>
  createWebhook(database.db, environmentId, {
    id: testId('wbh'),
    url: 'https://hooks.example.test/openverify',
    enabledEvents,
    secret: SECRET,
  });

async function delivery(nextAttemptAt?: Date) {
  const { environment } = await createTestTenant(database.db);
  const webhook = await newWebhook(environment.id);
  const event = await createEvent(database.db, environment.id, {
    id: testId('evt'),
    name: 'inquiry.completed',
    payload: {},
  });
  const created = await createWebhookDelivery(database.db, environment.id, {
    id: testId('whd'),
    webhookId: webhook.id,
    eventId: event.id,
    ...(nextAttemptAt === undefined ? {} : { nextAttemptAt }),
  });
  if (!created) throw new Error('delivery not created');
  return { environment, webhook, event, delivery: created };
}

describe('webhooks', () => {
  it('stores the signing secret encrypted and never returns it with the webhook', async () => {
    const { environment } = await createTestTenant(database.db);

    const webhook = await newWebhook(environment.id);
    const raw = await database.db.execute<{ secret: string }>(
      sql`select secret from webhooks where id = ${webhook.id}`,
    );

    expect(webhook).toMatchObject({
      environmentId: environment.id,
      url: 'https://hooks.example.test/openverify',
      enabledEvents: ['inquiry.completed'],
      status: 'enabled',
      secretLast4: LAST4,
    });
    expect(webhook).not.toHaveProperty('secret');
    expect(raw.rows[0]?.secret).toMatch(/^ov1\./);
    expect(raw.rows[0]?.secret).not.toContain(SECRET.slice(7));
    expect(await getWebhook(database.db, environment.id, webhook.id)).toEqual(webhook);
    expect(await getWebhookSigningSecret(database.db, environment.id, webhook.id)).toBe(SECRET);
  });

  it('updates the url, enabled events and status', async () => {
    const { environment } = await createTestTenant(database.db);
    const webhook = await newWebhook(environment.id);

    const updated = await updateWebhook(database.db, environment.id, webhook.id, {
      url: 'https://hooks.example.test/v2',
      enabledEvents: ['*'],
      status: 'disabled',
    });

    expect(updated).toMatchObject({
      url: 'https://hooks.example.test/v2',
      enabledEvents: ['*'],
      status: 'disabled',
      secretLast4: LAST4,
    });
    expect(updated).not.toHaveProperty('secret');
    expect(await updateWebhook(database.db, environment.id, webhook.id, {})).toEqual(updated);
  });

  it('lists webhooks newest first with cursor pagination', async () => {
    onTestFinished(wallClockStepsBack());
    const { environment } = await createTestTenant(database.db);
    const clock = createdAtClock(database.db);
    const first = await clock.stamp('webhooks', await newWebhook(environment.id));
    const second = await clock.stamp('webhooks', await newWebhook(environment.id));

    const page = await listWebhooks(database.db, environment.id, { size: 1 });

    expect(page.items.map((webhook) => webhook.id)).toEqual([second.id]);
    expect(page.items[0]).not.toHaveProperty('secret');
    expect(
      (await listWebhooks(database.db, environment.id, { after: page.next ?? '' })).items,
    ).toEqual([first]);
    await expect(
      listWebhooks(database.db, environment.id, { after: testId('wbh') }),
    ).rejects.toBeInstanceOf(InvalidCursorError);
  });

  it('finds the enabled webhooks subscribed to an event, including wildcards', async () => {
    const { environment } = await createTestTenant(database.db);
    const specific = await newWebhook(environment.id, ['inquiry.completed', 'inquiry.failed']);
    const wildcard = await newWebhook(environment.id, ['*']);
    await newWebhook(environment.id, ['verification.passed']);
    const disabled = await newWebhook(environment.id, ['*']);
    await updateWebhook(database.db, environment.id, disabled.id, { status: 'disabled' });

    const subscribed = await listWebhooksForEvent(database.db, environment.id, 'inquiry.completed');

    expect(subscribed.map((webhook) => webhook.id).sort()).toEqual(
      [specific.id, wildcard.id].sort(),
    );
    expect(subscribed[0]).not.toHaveProperty('secret');
  });

  it('keeps webhooks inside their environment', async () => {
    const { environment } = await createTestTenant(database.db);
    const webhook = await newWebhook(environment.id, ['*']);
    const other = await createTestTenant(database.db);

    expect(await getWebhook(database.db, other.environment.id, webhook.id)).toBeNull();
    expect(await getWebhookSigningSecret(database.db, other.environment.id, webhook.id)).toBeNull();
    expect(
      await updateWebhook(database.db, other.environment.id, webhook.id, { status: 'disabled' }),
    ).toBeNull();
    expect(
      await listWebhooksForEvent(database.db, other.environment.id, 'inquiry.created'),
    ).toEqual([]);
    expect((await listWebhooks(database.db, other.environment.id)).items).toEqual([]);
  });
});

describe('a subject with several links (C107.4)', () => {
  async function filtered(filters: WebhookFilters) {
    const { environment } = await createTestTenant(database.db);
    const webhook = await newWebhook(environment.id, ['*']);
    await updateWebhook(database.db, environment.id, webhook.id, { filters });
    return { environmentId: environment.id, webhook };
  }
  const found = async (environmentId: string, subject: EventSubject) =>
    (await listWebhooksForEvent(database.db, environmentId, 'transaction.created', subject)).map(
      (row) => row.id,
    );

  it('passes a filter that allows any one of them', async () => {
    const { environmentId, webhook } = await filtered({ 'account-type-ids': ['acctp_b'] });

    expect(
      await found(environmentId, { strict: true, accountTypeIds: ['acctp_a', 'acctp_b'] }),
    ).toEqual([webhook.id]);
  });

  it('fails a filter that allows none of them', async () => {
    const { environmentId } = await filtered({ 'inquiry-template-ids': ['itmpl_z'] });

    expect(
      await found(environmentId, { strict: true, inquiryTemplateIds: ['itmpl_a', 'itmpl_b'] }),
    ).toEqual([]);
  });

  it('holds a strict subject with an empty list to the strict rule', async () => {
    const { environmentId } = await filtered({ 'inquiry-template-ids': ['itmpl_a'] });

    expect(await found(environmentId, { strict: true, inquiryTemplateIds: [] })).toEqual([]);
  });

  it('passes a webhook with no filter, whatever the links', async () => {
    const { environment } = await createTestTenant(database.db);
    const webhook = await newWebhook(environment.id, ['*']);

    expect(await found(environment.id, { strict: true, accountTypeIds: ['acctp_a'] })).toEqual([
      webhook.id,
    ]);
    expect(await found(environment.id, { strict: true })).toEqual([webhook.id]);
  });

  it('reads a single link beside the list', async () => {
    const { environmentId, webhook } = await filtered({ 'account-type-ids': ['acctp_a'] });

    expect(
      await found(environmentId, { accountTypeId: 'acctp_a', accountTypeIds: ['acctp_b'] }),
    ).toEqual([webhook.id]);
  });
});

describe('webhook deliveries', () => {
  it('creates one pending delivery per webhook and event', async () => {
    const { environment, webhook, event, delivery: created } = await delivery();

    expect(created).toMatchObject({
      environmentId: environment.id,
      webhookId: webhook.id,
      eventId: event.id,
      status: 'pending',
      attemptCount: 0,
      attempts: [],
      lastAttemptAt: null,
      deliveredAt: null,
    });
    expect(created.nextAttemptAt).toBeInstanceOf(Date);
    expect(
      await createWebhookDelivery(database.db, environment.id, {
        id: testId('whd'),
        webhookId: webhook.id,
        eventId: event.id,
      }),
    ).toBeNull();
    expect(await getWebhookDelivery(database.db, environment.id, created.id)).toEqual(created);
  });

  it('lists pending deliveries that are due, oldest first, across environments', async () => {
    const now = new Date('2030-01-01T00:00:00.000Z');
    const early = await delivery(new Date('2029-12-31T23:00:00.000Z'));
    const late = await delivery(new Date('2029-12-31T23:30:00.000Z'));
    const future = await delivery(new Date('2030-01-01T00:05:00.000Z'));

    const due = await listDueWebhookDeliveries(database.db, { now, limit: 1000 });
    const ids = due.map((item) => item.id);

    expect(ids.indexOf(early.delivery.id)).toBeGreaterThanOrEqual(0);
    expect(ids.indexOf(early.delivery.id)).toBeLessThan(ids.indexOf(late.delivery.id));
    expect(ids).not.toContain(future.delivery.id);
    expect(await listDueWebhookDeliveries(database.db, { now, limit: 1 })).toHaveLength(1);
  });

  it('can lock due deliveries inside a transaction', async () => {
    const { delivery: created } = await delivery(new Date('2000-01-01T00:00:00.000Z'));

    const locked = await database.db.transaction((tx) =>
      listDueWebhookDeliveries(tx, { now: new Date('2000-01-01T00:00:01.000Z'), lock: true }),
    );

    expect(locked.map((item) => item.id)).toContain(created.id);
  });

  it('records a retry, then success, keeping every attempt', async () => {
    const { environment, delivery: created } = await delivery();
    const first = new Date('2026-10-20T10:00:00.000Z');
    const retryAt = new Date('2026-10-20T10:00:30.000Z');

    const retried = await recordWebhookDeliveryAttempt(database.db, environment.id, created.id, {
      outcome: 'retry',
      attemptedAt: first,
      responseStatus: 503,
      durationMs: 120,
      error: 'HTTP 503',
      nextAttemptAt: retryAt,
    });
    const succeeded = await recordWebhookDeliveryAttempt(database.db, environment.id, created.id, {
      outcome: 'succeeded',
      attemptedAt: retryAt,
      responseStatus: 204,
      durationMs: 80,
    });

    expect(retried).toMatchObject({
      status: 'pending',
      attemptCount: 1,
      nextAttemptAt: retryAt,
      lastAttemptAt: first,
      lastResponseStatus: 503,
      lastError: 'HTTP 503',
    });
    expect(succeeded).toMatchObject({
      status: 'succeeded',
      attemptCount: 2,
      nextAttemptAt: null,
      lastResponseStatus: 204,
      lastError: null,
      deliveredAt: retryAt,
    });
    expect(succeeded?.attempts).toEqual([
      {
        attempt: 1,
        attempted_at: '2026-10-20T10:00:00.000Z',
        response_status: 503,
        duration_ms: 120,
        error: 'HTTP 503',
      },
      {
        attempt: 2,
        attempted_at: '2026-10-20T10:00:30.000Z',
        response_status: 204,
        duration_ms: 80,
        error: null,
      },
    ]);
  });

  it('gives up after a failed attempt and ignores attempts on finished deliveries', async () => {
    const { environment, delivery: created } = await delivery();

    const failed = await recordWebhookDeliveryAttempt(database.db, environment.id, created.id, {
      outcome: 'failed',
      attemptedAt: new Date(),
      error: 'connect ECONNREFUSED',
    });

    expect(failed).toMatchObject({
      status: 'failed',
      attemptCount: 1,
      nextAttemptAt: null,
      lastResponseStatus: null,
      deliveredAt: null,
    });
    expect(
      await recordWebhookDeliveryAttempt(database.db, environment.id, created.id, {
        outcome: 'succeeded',
        attemptedAt: new Date(),
      }),
    ).toBeNull();
  });

  it('truncates long error messages', async () => {
    const { environment, delivery: created } = await delivery();

    const recorded = await recordWebhookDeliveryAttempt(database.db, environment.id, created.id, {
      outcome: 'failed',
      attemptedAt: new Date(),
      error: 'x'.repeat(5000),
    });

    expect(recorded?.lastError).toHaveLength(1000);
    expect(recorded?.attempts[0]?.error).toHaveLength(1000);
  });

  it('keeps deliveries inside their environment', async () => {
    const { delivery: created, webhook } = await delivery();
    const other = await createTestTenant(database.db);
    const otherEvent = await createEvent(database.db, other.environment.id, {
      id: testId('evt'),
      name: 'inquiry.created',
      payload: {},
    });

    expect(await getWebhookDelivery(database.db, other.environment.id, created.id)).toBeNull();
    expect(
      await recordWebhookDeliveryAttempt(database.db, other.environment.id, created.id, {
        outcome: 'succeeded',
        attemptedAt: new Date(),
      }),
    ).toBeNull();
    await expect(
      createWebhookDelivery(database.db, other.environment.id, {
        id: testId('whd'),
        webhookId: webhook.id,
        eventId: otherEvent.id,
      }),
    ).rejects.toThrow();
  });
});
