/**
 * C281: the record test of the hand-written sharing guide under `docs/connect/` (its facts are the
 * repository's, so a test holds them): every page is written (no stub marker); every event name,
 * scope and variable it names exists (`EVENT_NAMES`, `PERMISSIONS`, `CONFIG_REGISTRY`); every
 * relative link and repository path it cites exists; every bold "Ours" label carries its reason
 * (C281.2); and the statements C281.1 and KP11-22 require are present where a reader would
 * otherwise assume the opposite.
 */
