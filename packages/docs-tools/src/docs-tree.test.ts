import { describe, expect, it } from 'vitest';
import {
  DOCS_TREE,
  DRAFT_MARKER_PREFIX,
  draftMarker,
  draftsRemaining,
  missingFromTree,
  stubFor,
  type DocsTreeEntry,
} from './docs-tree.js';
import { REPOSITORY_ROOT, createMemoryRepository, createRepository } from './repository.js';
import { AREA_OWNERS } from './types.js';

const paths = DOCS_TREE.map((item) => item.path);

function entryAt(path: string): DocsTreeEntry {
  const found = DOCS_TREE.find((item) => item.path === path);
  if (found === undefined) throw new Error(`no manifest entry ${path}`);
  return found;
}
const OWNERS = new Set([...Object.values(AREA_OWNERS), 'contracts-11e']);

/** C277.1's and C281.1's named pages. */
const SELF_HOSTING = [
  'README.md',
  'install-compose.md',
  'install-kubernetes.md',
  'requirements.md',
  'configuration.md',
  'sizing.md',
  'secrets-and-rotation.md',
  'backups-and-restore.md',
  'upgrades.md',
  'database.md',
  'valkey.md',
  'first-run.md',
  'break-glass.md',
  'monitoring.md',
  'hardening-checklist.md',
  'verify-artifacts.md',
];
const CONNECT = [
  'README.md',
  'connections.md',
  'share-tokens.md',
  'consent.md',
  'peek-and-redeem.md',
  'provenance.md',
  'client-side.md',
  'events-and-workflows.md',
  'mapping.md',
  'limits.md',
];

describe('the docs tree manifest', () => {
  it('lists each path once, sorted, each with a known owner, a title and a contract', () => {
    expect(paths).toEqual([...new Set(paths)].sort());
    for (const item of DOCS_TREE) {
      expect(OWNERS.has(item.owner), item.path).toBe(true);
      expect(item.title.length, item.path).toBeGreaterThan(0);
      expect(item.contract.split('.')[0], item.path).toMatch(/^C2\d\d$/);
    }
  });

  it('covers C273 to C281 and C284: every page C277.1 and C281.1 name, and the generated files', () => {
    expect(paths).toEqual(
      expect.arrayContaining(SELF_HOSTING.map((file) => `docs/self-hosting/${file}`)),
    );
    expect(paths).toEqual(expect.arrayContaining(CONNECT.map((file) => `docs/connect/${file}`)));
    expect(paths).toEqual(
      expect.arrayContaining([
        'SECURITY.md',
        'docs/security/threat-model.md',
        'docs/security/asvs-5.0.0-l2.csv',
        'docs/security/masvs-2.1.0.csv',
        'docs/security/crypto-inventory.md',
        'docs/security/data-classification.md',
        'docs/security/logging.md',
        'docs/security/vulnerability-policy.md',
        'docs/security/README.md',
        'docs/compliance/README.md',
        'docs/compliance/roles.md',
        'docs/checks/catalog.md',
        'docs/checks/limits.json',
        'docs/api/README.md',
        'docs/migration/from-persona.md',
        'docs/release/checklist.md',
        'docs/release/notes.md',
      ]),
    );
    expect(DOCS_TREE.filter((item) => item.generated).map((item) => item.path)).toEqual([
      'docs/api/README.md',
      'docs/checks/catalog.md',
      'docs/compliance/record-of-processing.md',
      'docs/connect/mapping.md',
      'docs/migration/from-persona.md',
      'docs/release/notes.md',
      'docs/security/asvs-5.0.0-l2-ids.txt',
      'docs/security/asvs-summary.md',
      'docs/security/data-classification.md',
      'docs/security/masvs-2.1.0-ids.txt',
      'docs/self-hosting/configuration.md',
      'docs/self-hosting/hardening-checklist.md',
    ]);
  });

  it('never lists the pages earlier Phases wrote, which the guides index', () => {
    expect(paths).not.toContain('docs/compliance/automated-decisions.md');
    expect(paths).not.toContain('docs/compliance/session-integrity.md');
    expect(paths).not.toContain('docs/api/openapi.json');
  });
});

describe('the stubs', () => {
  const markdown: DocsTreeEntry = {
    path: 'docs/x/a.md',
    title: 'A page',
    owner: 'docs-records',
    contract: 'C276.1',
    generated: false,
  };

  it('hold the title, the marker naming the owner, and what the owner writes', () => {
    expect(draftMarker('docs-records')).toBe('Draft: written in Workflow 11E by docs-records');
    expect(stubFor(markdown)).toBe(
      '# A page\n\nDraft: written in Workflow 11E by docs-records\n\nWritten by `docs-records` (C276.1) in Workflow 11E; this stub keeps the path resolving until then.\n',
    );
    expect(stubFor({ ...markdown, generated: true })).toContain('Generated by `docs-records`');
    expect(stubFor({ ...markdown, path: 'docs/x/a.csv' })).toBe(
      'Draft: written in Workflow 11E by docs-records\n',
    );
    expect(JSON.parse(stubFor({ ...markdown, path: 'docs/x/a.json' }))).toEqual({
      draft: 'Draft: written in Workflow 11E by docs-records',
      title: 'A page',
    });
  });

  it('are found missing and found remaining, with the owner each marker names', () => {
    const repo = createMemoryRepository({
      'docs/security/README.md': stubFor(entryAt('docs/security/README.md')),
      'docs/security/logging.md': '# Logging inventory\n\nWritten.\n',
    });

    expect(missingFromTree(repo).map((item) => item.path)).not.toContain('docs/security/README.md');
    expect(missingFromTree(repo)).toHaveLength(DOCS_TREE.length - 2);
    expect(draftsRemaining(repo)).toEqual([
      { path: 'docs/security/README.md', marker: 'Draft: written in Workflow 11E by docs-records' },
    ]);
  });
});

describe('the repository', () => {
  const repo = createRepository(REPOSITORY_ROOT);

  it('holds every manifest path', () => {
    expect(missingFromTree(repo)).toEqual([]);
  });

  it('holds no marker that names another owner than the manifest, and none in the id lists', () => {
    for (const { path, marker } of draftsRemaining(repo)) {
      const owner = DOCS_TREE.find((item) => item.path === path)?.owner ?? '';
      expect(marker, path).toContain(`${DRAFT_MARKER_PREFIX}${owner}`);
    }
    const remaining = draftsRemaining(repo).map((item) => item.path);
    expect(remaining).not.toContain('docs/security/asvs-5.0.0-l2-ids.txt');
    expect(remaining).not.toContain('docs/security/masvs-2.1.0-ids.txt');
  });
});
