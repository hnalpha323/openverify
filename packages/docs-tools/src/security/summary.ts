/**
 * C274.3 (Workflow 11E, docs-security): the generated `docs/security/asvs-summary.md`, the counts per
 * ASVS chapter and MASVS group and per status, rendered from the two committed checklists. It reads
 * nothing else: no clock, no git (C274.6's staleness is a check, `checkSecurityWith`, so a later edit
 * elsewhere never makes this page differ from a fresh render).
 */
import { SECURITY_CHECKLIST_STATUSES, type SecurityChecklistRow } from './checklist.js';

export const ASVS_SUMMARY_PATH = 'docs/security/asvs-summary.md';

/** The status columns, in the order the tables show them. */
const COLUMNS = ['met', 'partial', 'gap', 'not_applicable', 'operator'] as const;

/** `v5.0.0-12.3.1` → `V12`; a MASVS id keeps its group (the `level` column). */
const asvsChapter = (row: SecurityChecklistRow): string =>
  `V${row.id.replace(/^v\d+\.\d+\.\d+-/, '').split('.')[0] ?? ''}`;
const masvsGroup = (row: SecurityChecklistRow): string => row.level;

const chapterNumber = (chapter: string): number => Number(chapter.slice(1));

/** One count table: a row per key, a column per status, a total column and an `All` row. */
function countTable(
  rows: readonly SecurityChecklistRow[],
  keyOf: (row: SecurityChecklistRow) => string,
  keys: readonly string[],
  label: string,
): string[] {
  const counts = new Map<string, Map<string, number>>();
  for (const row of rows) {
    const key = keyOf(row);
    const byStatus = counts.get(key) ?? new Map<string, number>();
    byStatus.set(row.status, (byStatus.get(row.status) ?? 0) + 1);
    counts.set(key, byStatus);
  }
  const line = (name: string, of: (status: string) => number): string => {
    const cells = COLUMNS.map((status) => of(status));
    const total = cells.reduce((sum, value) => sum + value, 0);
    return `| ${name} | ${cells.map(String).join(' | ')} | ${String(total)} |`;
  };
  return [
    `| ${label} | ${COLUMNS.join(' | ')} | total |`,
    `|---|${COLUMNS.map(() => '---:').join('|')}|---:|`,
    ...keys.map((key) => line(key, (status) => counts.get(key)?.get(status) ?? 0)),
    line('All', (status) => rows.filter((row) => row.status === status).length),
  ];
}

/** The ids of the rows in `status`, as a backticked, comma-separated list (or "none"). */
function idsIn(rows: readonly SecurityChecklistRow[], status: string): string {
  const ids = rows.filter((row) => row.status === status).map((row) => `\`${row.id}\``);
  return ids.length === 0 ? 'none' : ids.join(', ');
}

/** The reviews a checklist holds: each date and commit with its row count, newest first. */
function reviewTable(rows: readonly SecurityChecklistRow[]): string[] {
  const counts = new Map<string, number>();
  for (const row of rows) {
    const key = `${row.reviewedAt}\u0000${row.reviewedCommit}`;
    counts.set(key, (counts.get(key) ?? 0) + 1);
  }
  const keys = [...counts.keys()].sort((a, b) => (a < b ? 1 : a > b ? -1 : 0));
  return [
    '| reviewed_at | reviewed_commit | rows |',
    '|---|---|---:|',
    ...keys.map((key) => {
      const [at = '', commit = ''] = key.split('\u0000');
      return `| ${at} | \`${commit}\` | ${String(counts.get(key) ?? 0)} |`;
    }),
  ];
}

/** Renders the summary page from the two checklists' rows. */
export function renderAsvsSummary(
  asvs: readonly SecurityChecklistRow[],
  masvs: readonly SecurityChecklistRow[],
): string {
  const chapters = [...new Set(asvs.map(asvsChapter))].sort(
    (a, b) => chapterNumber(a) - chapterNumber(b),
  );
  const groups = [...new Set(masvs.map(masvsGroup))];
  const statuses = SECURITY_CHECKLIST_STATUSES.join(', ');
  const lines = [
    '# ASVS and MASVS summary',
    '',
    'Generated by `pnpm --filter @openverify/docs-tools docs:security` from',
    '[`asvs-5.0.0-l2.csv`](asvs-5.0.0-l2.csv) and [`masvs-2.1.0.csv`](masvs-2.1.0.csv); do not edit',
    'it by hand. A test fails when this page differs from a fresh render (C274.3).',
    '',
    'OpenVerify is self-assessed against OWASP ASVS 5.0.0 Level 2 and, for the Android SDK, against',
    "OWASP MASVS v2.1.0. These are the project's own statuses with evidence a reader can follow; OWASP",
    "certifies nothing, and no certification is claimed. Most rows rest on the project's own tests,",
    "which share its blind spots (C274.7). The checklists hold only the standards' ids and our words:",
    'the requirement texts are CC BY-SA 4.0 and are never committed (`scripts/fetch_asvs.py` and',
    '`scripts/fetch_masvs.py` fetch them for local reading).',
    '',
    `The statuses are ${statuses}.`,
    'A row is `met` only when it is met on every supported install path (compose and the chart) and',
    'cites a test or check that ran locally; `operator` rows are what only the deployment can meet,',
    'and the self-hosting hardening checklist carries each one. The threat ids the rows cite are in',
    '[the threat model](threat-model.md).',
    '',
    '## ASVS 5.0.0 Level 2, by chapter',
    '',
    ...countTable(asvs, asvsChapter, chapters, 'chapter'),
    '',
    `Operator rows: ${idsIn(asvs, 'operator')}.`,
    '',
    `Gap rows: ${idsIn(asvs, 'gap')}.`,
    '',
    '## MASVS v2.1.0, by group',
    '',
    'The rows cover the three published Android modules, `openverify-sdk`, `openverify-nfc` and',
    "`openverify-face` (`demo-app` is not shipped). The `level` column holds each control's group,",
    'because MASVS v2 controls carry no level. A library checklist covers the SDK, not the host app it',
    "runs in: the host app's own MASVS duties remain (C275.4).",
    '',
    ...countTable(masvs, masvsGroup, groups, 'group'),
    '',
    `Operator rows: ${idsIn(masvs, 'operator')}.`,
    '',
    `Gap rows: ${idsIn(masvs, 'gap')}.`,
    '',
    '## Reviews',
    '',
    'Each row records the date and the commit its evidence was read at. A row is stale when a file',
    'it cites changed after its `reviewed_commit` (C274.6); that is computed from git by',
    '`checkSecurityWith` in `packages/docs-tools/src/security/`, never on this page, so the page',
    'depends on the checklists alone.',
    '',
    '### ASVS',
    '',
    ...reviewTable(asvs),
    '',
    '### MASVS',
    '',
    ...reviewTable(masvs),
    '',
  ];
  return lines.join('\n');
}
