"""Write packages/checks/src/data/iso3166.ts, the ISO 3166-1 table of the checks (C33).

The table comes from the MIT-licensed `iso3166` package, a dev dependency of the vision service,
so run it with that environment:

    cd services/vision && uv run --frozen python ../../packages/checks/scripts/generate-iso3166.py

then format the output with `pnpm exec prettier --write packages/checks/src/data/iso3166.ts`.
It keeps the alpha-2, alpha-3 and numeric codes only. The user-assigned XK (Kosovo) is left out:
it is not an ISO 3166-1 code, and ICAO writes Kosovo as RKS (Doc 9303 Part 3 §5), which
`icao-codes.ts` maps.
"""

from __future__ import annotations

import sys
from importlib.metadata import version
from pathlib import Path

import iso3166

OUTPUT = Path(__file__).resolve().parent.parent / "src" / "data" / "iso3166.ts"
USER_ASSIGNED = frozenset({"XK"})


def render() -> str:
    rows = sorted(
        (country.alpha2, country.alpha3, country.numeric)
        for country in iso3166.countries
        if country.alpha2 not in USER_ASSIGNED
    )
    body = "\n".join(
        f"  ['{alpha2}', '{alpha3}', '{numeric}']," for alpha2, alpha3, numeric in rows
    )
    return (
        "/**\n"
        " * ISO 3166-1 alpha-2, alpha-3 and numeric codes (C33), the only copy in OpenVerify.\n"
        " *\n"
        " * GENERATED by `packages/checks/scripts/generate-iso3166.py` from the MIT-licensed\n"
        f" * `iso3166` {version('iso3166')} package. Do not edit by hand; re-run the script\n"
        " * instead.\n"
        " * The user-assigned XK (Kosovo) is left out: ICAO writes it RKS (`icao-codes.ts`).\n"
        " */\n"
        "export const ISO3166_SOURCE = {\n"
        "  package: 'iso3166',\n"
        f"  version: '{version('iso3166')}',\n"
        "  license: 'MIT',\n"
        "} as const;\n"
        "\n"
        "/** Every ISO 3166-1 entry, sorted by alpha-2 code. */\n"
        "export const ISO3166_COUNTRIES: readonly (readonly [\n"
        "  alpha2: string,\n"
        "  alpha3: string,\n"
        "  numeric: string,\n"
        "])[] = [\n"
        f"{body}\n"
        "];\n"
    )


def main() -> int:
    OUTPUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
