const limitRows = (
  limits: Readonly<Record<string, StatedLimit>>,
  codes: Readonly<Record<string, string>> = {},
): string[] =>
  Object.entries(limits).map(
    ([name, { value, basis, source }]) =>
      `| \`${name}\` | ${String(value)} | ${basis} | ${codes[name] === undefined ? '' : `\`${codes[name]}\``} | ${source} |`,
  );

