/**
 * The dev-only builder of the generated report tables (`packages/checks/data/reports/`), run by a
 * person after `python3 scripts/fetch_data.py`, never at run time and never in CI:
 *
 *     pnpm --filter @openverify/checks exec node --conditions=@openverify/source \
 *       --import ./scripts/register-ts.mjs src/reports/build-data.ts
 *
 * It reads only pinned `data/manifest.json` files, refusing any whose SHA-256 differs, and writes:
 * - `email-tables-check.json`: the authored free-mail and relay domains checked against the pinned
 *   disposable list (C82.1's build test); it refuses to write while any domain is listed;
 * - `us-zip-prefixes.json`: the US state ZIP prefixes of libaddressinput (C82.3; CC BY 4.0).
 */

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseDisposableDomainList } from '../contact/disposable-domains.js';
import { US_ZIP_PREFIXES_FILE, parseUsZipPrefixes } from './address/us-zip.js';
import { REPORT_DATA_DIRECTORY } from './data.js';
import {
  emailTablesDigest,
  findDisposableOverlaps,
  freeMailDomains,
  relayDomains,
} from './email/tables.js';

/** A `data/manifest.json` entry, as far as the builder reads it. */
export interface ManifestEntry {
  readonly name: string;
  readonly filename: string;
  readonly sha256: string;
  readonly license: string;
}

/** A pinned source a generated table records. */
export interface ReportDataSource {
  readonly name: string;
  readonly sha256: string;
  readonly license: string;
}

/** The disposable-list check of the authored email tables. */
export interface EmailTablesCheck {
  readonly description: string;
  /** `emailTablesDigest()` when the check ran. */
  readonly 'tables-sha256': string;
  readonly disposable: ReportDataSource;
  /** Always empty: the builder refuses to write otherwise. */
  readonly overlaps: readonly string[];
}

/** The generated table of the disposable check. */
export const EMAIL_TABLES_CHECK_FILE = 'email-tables-check.json';

const DISPOSABLE_SOURCE = 'disposable_email_domains';
const COUNTRY_INFO_SOURCE = 'libaddressinput_countryinfo';

const sourceOf = ({ name, sha256, license }: ManifestEntry): ReportDataSource => ({
  name,
  sha256,
  license,
});

/**
 * Checks the authored free-mail and relay domains against the disposable list's text.
 * @throws {Error} naming each domain the list holds.
 */
export function emailTablesCheck(disposableText: string, entry: ManifestEntry): EmailTablesCheck {
  const listed = parseDisposableDomainList(disposableText);
  const overlaps = findDisposableOverlaps([...freeMailDomains(), ...relayDomains()], listed);
  if (overlaps.length > 0) {
    throw new Error(`the disposable list names authored email domains: ${overlaps.join(', ')}`);
  }
  return {
    description:
      'OpenVerify email tables check (plan C82.1, the build test): no free-mail or relay domain of free-mail-domains.json and relay-domains.json is on the pinned disposable list, by itself or a parent. Generated by packages/checks/src/reports/build-data.ts; never edit by hand. The test fails when the tables or the pin change until the builder runs again.',
    'tables-sha256': emailTablesDigest(),
    disposable: sourceOf(entry),
    overlaps,
  };
}

/** A table as written: two-space JSON, final newline. */
export function serializeReportTable(table: unknown): string {
  return `${JSON.stringify(table, null, 2)}\n`;
}

/**
 * Builds every generated table from the pinned files under `root/data/`, keyed by file name.
 * @throws {Error} for a source missing from the manifest, or a file that is not the pinned one.
 */
export function buildReportData(root: string): Record<string, string> {
  const manifest = (
    JSON.parse(readFileSync(join(root, 'data', 'manifest.json'), 'utf8')) as {
      data: ManifestEntry[];
    }
  ).data;
  const pinned = (name: string): { entry: ManifestEntry; text: string } => {
    const entry = manifest.find((candidate) => candidate.name === name);
    if (entry === undefined) {
      throw new Error(`${name} is not in data/manifest.json`);
    }
    const bytes = readFileSync(join(root, 'data', entry.filename));
    if (createHash('sha256').update(bytes).digest('hex') !== entry.sha256) {
      throw new Error(`data/${entry.filename} is not the pinned file; run scripts/fetch_data.py`);
    }
    return { entry, text: bytes.toString('utf8') };
  };
  const disposable = pinned(DISPOSABLE_SOURCE);
  const countryInfo = pinned(COUNTRY_INFO_SOURCE);
  return {
    [EMAIL_TABLES_CHECK_FILE]: serializeReportTable(
      emailTablesCheck(disposable.text, disposable.entry),
    ),
    [US_ZIP_PREFIXES_FILE]: serializeReportTable({
      description:
        "OpenVerify US ZIP prefixes per state and territory (plan C82.3): a ZIP is consistent with a state when its first digits match the state's pattern. Generated by packages/checks/src/reports/build-data.ts from data/manifest.json's libaddressinput_countryinfo; never edit by hand.",
      licence:
        "The prefix patterns are libaddressinput's (data/US sub_keys and sub_zips), Google's address metadata, licensed under CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/). Modified: only those two members are kept. See packages/checks/data/reports/NOTICE.",
      sources: [sourceOf(countryInfo.entry)],
      states: parseUsZipPrefixes(countryInfo.text),
    }),
  };
}

/** The command-line entry, run by a person (see the module comment). */
function main(): void {
  const root = join(REPORT_DATA_DIRECTORY, '..', '..', '..', '..');
  for (const [file, text] of Object.entries(buildReportData(root))) {
    writeFileSync(join(REPORT_DATA_DIRECTORY, file), text);
    process.stdout.write(`wrote ${file} (${String(Buffer.byteLength(text))} bytes)\n`);
  }
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
